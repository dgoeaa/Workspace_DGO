#!/usr/bin/env node
// Writes config/platforms.data.js — the browser's copy of the platform registry, used by the
// Runtime's Platforms menu (docs/architecture/PLATFORM_ACCESS_SPEC.md FR-7, §6.3).
//
//   node scripts/build-platforms-data.mjs          write it
//   node scripts/build-platforms-data.mjs --check  exit 1 if the committed file is stale
//
// Generated rather than imported because the runtime is zero-build and cannot import a
// Node module that reaches for node:os and node:path. Only what publicView() allows is copied.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { Audiences, Platforms, ROOT } from './platforms.config.mjs';

const OUT = path.join(ROOT, 'config', 'platforms.data.js');

export function render() {
  const platforms = Platforms.map(p => ({
    id: p.id, name: p.name, purpose: p.purpose, audience: p.audience, category: p.category,
    exposure: p.exposure, port: p.port, openPath: p.openPath, prodUrl: p.prodUrl ?? null,
    fallbackFor: p.fallbackFor ?? null,
  }));
  const audiences = Audiences.map(a => ({ id: a.id, label: a.label, roles: [...a.roles] }));
  return `// GENERATED by scripts/build-platforms-data.mjs from scripts/platforms.config.mjs — do not edit.
// Regenerate with: npm run platforms:data

export const PlatformAudiences = Object.freeze(${JSON.stringify(audiences, null, 2)});

export const PlatformLinks = Object.freeze(${JSON.stringify(platforms, null, 2)});

/** Platforms this role may see. Advisory while auth is inert: it decides what is shown. */
export function platformsVisibleTo(role) {
  return PlatformLinks.filter(p => {
    const a = PlatformAudiences.find(x => x.id === p.audience);
    return Boolean(a) && (a.roles.includes('*') || a.roles.includes(role));
  });
}

/**
 * Where a platform answers from this page. Served locally: the same host on its port.
 * Served from a real host: its production URL, or null when it has none (a local-only
 * tool, which the menu then leaves out rather than pointing at a port that is not there).
 */
export function platformHref(p, loc = globalThis.location) {
  const host = loc?.hostname || 'localhost';
  const local = host === 'localhost' || host === '127.0.0.1' || host.endsWith('.app.github.dev');
  if (!local) return p.prodUrl || null;
  const proto = loc?.protocol === 'https:' ? 'https:' : 'http:';
  return \`\${proto}//\${host}:\${p.port}\${p.openPath}\`;
}
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const want = render();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== want) { console.error('config/platforms.data.js is stale. Run: npm run platforms:data'); process.exit(1); }
    console.log('config/platforms.data.js matches the platform registry');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('wrote config/platforms.data.js');
  }
}
