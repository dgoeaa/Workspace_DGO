#!/usr/bin/env node
// Compile the internal platform's correspondence templates into the DGO Correspondence Mailer.
//
//   node scripts/build-mailer-letterhead.mjs           write mailer/js/letterhead.generated.js
//   node scripts/build-mailer-letterhead.mjs --check   exit 1 if it differs from the platform config
//
// The mailer ships standalone (releases/dgo-correspondence-mailer-*.zip) and cannot import from
// config/ at run time, so it carries a copy of config/correspondence-email-templates.config.js:
// the Agency letterhead's brand, the signatory defaults and the six templates' sections. This
// script writes that copy and --check holds it to the source, so a template edited in the
// platform and not recompiled here fails `npm run test:mailer` instead of quietly diverging.
//
// The letterhead MARKUP is not copied: it is code, in mailer/js/letterhead.js, and
// tests/mailer.test.mjs holds it byte-for-byte to render() in core/correspondence-email-service.js.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CorrespondenceEmailTemplateConfig as C } from '../config/correspondence-email-templates.config.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'mailer', 'js', 'letterhead.generated.js');

export function generated() {
  const data = { schema: C.schema, brand: C.brand, defaults: C.defaults, templates: C.templates };
  return `// GENERATED by scripts/build-mailer-letterhead.mjs from config/correspondence-email-templates.config.js.
// Do not edit: change the platform config and run \`npm run mailer:letterhead\`.
// These are the internal platform's six correspondence templates and its Agency letterhead
// brand, so the mailer sends the same letters the platform's Correspondence Email Desk does.

export const LETTERHEAD = Object.freeze(${JSON.stringify(data, null, 2)});
`;
}

function main() {
  const text = generated();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== text) { console.log('  ❌ mailer/js/letterhead.generated.js differs from the platform config — run: npm run mailer:letterhead'); process.exit(1); }
    console.log('  ✅ mailer/js/letterhead.generated.js matches config/correspondence-email-templates.config.js');
    return;
  }
  if (current !== text) fs.writeFileSync(OUT, text);
  console.log('  mailer/js/letterhead.generated.js current');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
