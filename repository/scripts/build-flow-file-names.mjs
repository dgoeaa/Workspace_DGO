#!/usr/bin/env node
/**
 * The flow artefact file name report (identifier catalogue namingConventions.flowArtifactFile, spec §17).
 *
 *   npm run flowfiles            write docs/folio-Master-Flows-and-Endpoints/reference/FLOW_FILE_NAMES.md
 *   npm run flowfiles -- --check fail if the report is out of date
 *
 * Every file about one flow names its endpoint, its flow and its tenant flow:
 * <CONTRACT_KEY>__<FlowName>__<flow-id8>[__<Part>].<kind>. Files generated or captured before the convention are listed
 * here with what their names lack, instead of being renamed blind: generators and registers resolve them by path, so each
 * adopts the convention when its generator is next changed. The report is advisory; tests/flow-artifact-names.test.mjs
 * enforces the convention where it has been adopted.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NOT_CAPTURED, parseFlowArtifactName } from './lib/flow-artifact-name.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const BASE = 'docs/folio-Master-Flows-and-Endpoints';
const OUT = `${BASE}/reference/FLOW_FILE_NAMES.md`;
const CHECK = process.argv.includes('--check');
const CAT = JSON.parse(readFileSync(join(ROOT, 'docs/reference/identification/identifier-catalogue.json'), 'utf8'));
const KEYS = Object.keys(CAT.contractKeyProcess).sort((a, b) => b.length - a.length);
const GUID = /[0-9a-f]{8}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{12}/i;

/* Where flow and endpoint artefacts live, one file per flow or per flow part. */
const SCOPES = [
  ['captures', 'Tenant captures of flow definitions'],
  ['contracts/deployed', 'Exported flow definitions'],
  ['surfaces', 'Designer-paste, delivered, console-apply and import packages'],
  ['packages', 'Paste packages (the generic kit blocks are exempt: they belong to no flow)'],
  ['provisioning/flows', 'Provisioning pages per flow'],
  ['provisioning/packages', 'Provisioning pages per package'],
  ['patches', 'Flow patches'],
  ['exports', 'Flow exports'],
  ['evidence', 'Run records and evidence'],
];
/* Not flow artefacts: the generic kit blocks, folder notes, and the list specification kept beside the packages. */
const EXEMPT = (rel) => /\/identification-kit\//.test(rel) || /(^|\/)sharepoint-lists\.json$/.test(rel) || /(^|\/)(README|CHANGES|INDEX)\.md$/i.test(rel) || /\/evidence\/(?!.*endpoint-runs)/.test(`/${rel}`) && !/endpoint-runs/.test(rel);
const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });

const rows = [];
for (const [scope, what] of SCOPES) {
  const abs = join(ROOT, BASE, scope);
  let files = []; try { files = walk(abs); } catch { continue; }
  for (const p of files.sort()) {
    const rel = relative(join(ROOT, BASE), p);
    if (EXEMPT(rel)) continue;
    const name = p.split('/').pop();
    const parsed = parseFlowArtifactName(name);
    const hasId = parsed ? parsed.id !== NOT_CAPTURED : GUID.test(name);
    const hasKey = parsed ? true : KEYS.some((k) => name.startsWith(`${k}__`) || name.startsWith(`${k}.`) || name.startsWith(`DGO_${k}.`));
    rows.push({ scope, what, rel, name, compliant: !!parsed && parsed.id !== NOT_CAPTURED, notCaptured: parsed?.id === NOT_CAPTURED, hasId, hasKey });
  }
}

const by = (s) => rows.filter((r) => r.scope === s);
const lacks = (r) => [!r.hasKey && 'contract key', !r.hasId && 'flow id', !r.compliant && r.hasKey && r.hasId && 'the <KEY>__<flow>__<id8> form'].filter(Boolean).join(', ');
const md = `# Flow artefact file names

**Generated by \`npm run flowfiles\` from \`scripts/build-flow-file-names.mjs\`. Do not edit by hand.**

Every file about one flow names its endpoint, its flow and its tenant flow
([spec §17](../../reference/identification/IDENTIFICATION_SYSTEM.md), *Flow artefact file*):

\`<CONTRACT_KEY>__<FlowName>__<flow-id8>[__<Part>].<kind>\`, for example
\`SUBMISSION__CG_Submission_Endpoint__de9ef13b.paste.json\` (the first 8 hex digits of the flow GUID; a part only
when a folder holds more than one file of that kind for the flow).

This report lists the flow and endpoint files in this folder and what each name lacks. It is advisory: files generated or
captured before 5 October 2026 keep their names until their generator adopts the convention, because generators and
registers resolve them by path. \`tests/flow-artifact-names.test.mjs\` enforces the convention where it is adopted.

| Folder | Files | Compliant | Flow id awaited | Not yet in the convention |
|---|---|---|---|---|
${SCOPES.filter(([s]) => by(s).length).map(([s, w]) => `| \`${s}\` (${w}) | ${by(s).length} | ${by(s).filter((r) => r.compliant).length} | ${by(s).filter((r) => r.notCaptured).length} | ${by(s).filter((r) => !r.compliant && !r.notCaptured).length} |`).join('\n')}
| **All** | **${rows.length}** | **${rows.filter((r) => r.compliant).length}** | **${rows.filter((r) => r.notCaptured).length}** | **${rows.filter((r) => !r.compliant && !r.notCaptured).length}** |

## Flow id awaited

These files follow the convention but name a flow the repository holds no capture or export of, so the id part is
\`${NOT_CAPTURED}\`. Supplying the flow's GUID (an export of the flow, or its id from the flow's address in Power Automate)
closes each.

${rows.filter((r) => r.notCaptured).map((r) => `- \`${r.rel}\``).join('\n') || 'None.'}

## Not yet in the convention

${SCOPES.filter(([s]) => by(s).some((r) => !r.compliant && !r.notCaptured)).map(([s]) => `### \`${s}\`

| File | Lacks |
|---|---|
${by(s).filter((r) => !r.compliant && !r.notCaptured).map((r) => `| \`${r.rel}\` | ${lacks(r)} |`).join('\n')}
`).join('\n')}`;

let cur = null; try { cur = readFileSync(join(ROOT, OUT), 'utf8'); } catch { /* new */ }
if (CHECK) {
  if (cur !== md) { console.error(`flow file name report is out of date — run: npm run flowfiles`); process.exit(1); }
  console.log(`flow file names: up to date (${rows.filter((r) => r.compliant).length} of ${rows.length} compliant)`);
} else {
  writeFileSync(join(ROOT, OUT), md);
  console.log(`flow file names: ${rows.length} files, ${rows.filter((r) => r.compliant).length} compliant, ${rows.filter((r) => r.notCaptured).length} awaiting a flow id`);
}
