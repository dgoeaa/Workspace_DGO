#!/usr/bin/env node
/**
 * The provisioning reference as something you can actually move through.
 *
 * WHAT WAS WRONG WITH READING IT
 *
 * The reference is complete and it is correct. It is also 131 markdown files and roughly
 * 195,000 lines, and every route through it is linear:
 *
 *   · The index is two flat tables — 77 deployed flows, then 54 packages. No search, no
 *     filter, no sort. Finding the flow behind a contract key means reading rows.
 *   · A flow page runs from 200 to 8,097 lines. `Web - Subsidiary Doc Actions` is 6,351;
 *     `Universal Dynamic_Multi-Actions_Executor` is 8,097. There is no outline, so
 *     "what does §7 say" is a scroll, and §13 — one block per action, 252 of them on that
 *     page — cannot be navigated at all.
 *   · Getting from one flow to another is: browser-back, find the row again, click.
 *   · The tables carry configured values, which are expressions and body templates and
 *     300-character JSON. On a narrow screen a markdown table with a cell like that stops
 *     being a table.
 *
 * None of that is fixed by writing the markdown differently. It is what a flat document set
 * is: the reference has an index and 131 documents, and a reader has one window.
 *
 * WHAT THIS BUILDS, AND WHAT IT DOES NOT
 *
 * It builds the DATA for an interface over exactly the same facts — `index.html`,
 * `console.css` and `console.js` beside it are authored, this generates only what they read.
 * The markdown stays, unchanged and still generated by `build-provisioning-reference.mjs`:
 * it is the diffable record, it is what `docs/reference/README.md` links, and a git diff of
 * a flow's provisioning is a thing worth keeping. The interface is a way through the same
 * material, not a replacement for it. Both render `scripts/lib/provisioning-model.mjs`, so
 * neither can show a fact the other cannot.
 *
 * NOTHING HERE RE-READS THE ESTATE. The packages were read, the registers joined and the
 * estate attributed once, in the model. This serialises that result and adds no fact to it.
 *
 * TWO FILES, AND WHY
 *
 * `fetch()` is blocked on `file://`, and this folder must stay one you can copy to a memory
 * stick and open — the same constraint `docs/visual/` documents. So data arrives as script
 * tags, and it is split:
 *
 *   provisioning-index.js    one summary per flow and a search haystack. Small, loaded in the
 *                            head, so the list, the search and the filters work on first
 *                            paint.
 *   provisioning-detail.js   every configured value, every action. Several megabytes, and
 *                            injected as a script tag after first paint, because making the
 *                            first render wait on it is the thing that makes a reference feel
 *                            slow to move through.
 *
 * ONE FILE, WHEN THE FOLDER IS THE PROBLEM
 *
 * `--standalone` folds the interface and both data tiers into a single HTML file. The folder
 * is the right shape in the repository — the data regenerates without touching the authored
 * files, and a diff of either stays readable. It is the wrong shape for handing the reference
 * to somebody: five files that only work together, in one directory, is an instruction people
 * get wrong. The single file is for that, and it is not committed — it is built on demand,
 * from the same data, and the `--check` above does not police it.
 *
 *   npm run provisioningconsole                 write the data
 *   npm run provisioningconsole -- --check      fail if it has drifted from the packages
 *   npm run provisioningconsole:one             one self-contained HTML file, whole estate
 *   npm run provisioningconsole:one -- --only=… the same, narrowed — see `--only` below
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { buildProvisioningModel, ROOT, OUT_DIR } from './lib/provisioning-model.mjs';
import { connectorOf, redactDeep, FAMILY } from './lib/provisioning-reader.mjs';
/* Byte order, not locale order. A locale-aware comparison returns different orderings on
   different hosts, so a generator that writes a tracked file with one produces a diff that
   depends on who ran it — which is why tests/preflight-addressing.test.mjs fails any generator
   under scripts/ that uses one. It caught this file. */
import { byteCompare } from './lib/stable-sort.mjs';

const check = process.argv.includes('--check');
const standalone = process.argv.includes('--standalone');
const onlyArg = (process.argv.find((a) => a.startsWith('--only=')) || '').slice('--only='.length);

/* ── selective export ─────────────────────────────────────────────────────────────────
 * `--only=` narrows what the export carries. Terms are comma-separated and OR'd, so one
 * flow, a handful, or a whole category are the same operation:
 *
 *   --only=flows/cg-submission-endpoint     one package, addressed exactly
 *   --only=CG_Submission_Endpoint           by the name on the flow
 *   --only=SUBMISSION                       by the contract key it serves
 *   --only=cg-*                             by glob, across names and slugs
 *   --only=portal                           an estate
 *   --only=deployed                         a package family
 *   --only=SUBMISSION,UPLOAD,portal         any mixture; the union of what each matches
 *
 * TWO RULES THAT ARE NOT NEGOTIABLE, BECAUSE A PARTIAL EXPORT IS A TRAP.
 *
 * A term that matches nothing FAILS the build. The alternative is an export that quietly
 * contains less than you asked for — and an export of the wrong size is indistinguishable
 * from an export of the right size once it is in someone's inbox.
 *
 * And a narrowed export never writes into docs/folio-Master-Flows-and-Endpoints/provisioning/. The committed data
 * is the whole estate by definition; a `--only` run that overwrote it would leave the
 * console silently showing one flow and claiming to be the reference.
 */
const ALIASES = {
  internal: (p) => p.estate === 'Internal platform',
  portal: (p) => p.estate === 'Document portal',
  deployed: (p) => p.part === 'deployed',
  live: (p) => p.part === 'deployed',
  design: (p) => p.family === 'design',
  release: (p) => p.family === 'release',
  paste: (p) => p.family === 'paste',
  undeployed: (p) => p.part !== 'deployed',
};

function selectPackages(all, keysOf) {
  if (!onlyArg) return { list: all, complete: true, terms: [] };
  const terms = onlyArg.split(',').map((t) => t.trim()).filter(Boolean);
  if (!terms.length) fail('--only= was given with no terms.');

  const chosen = new Map();
  const unmatched = [];
  for (const term of terms) {
    const low = term.toLowerCase();
    const glob = term.includes('*')
      ? new RegExp(`^${term.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*')}$`, 'i')
      : null;
    const hits = all.filter((pkg) => {
      if (ALIASES[low] && ALIASES[low](pkg)) return true;
      const id = `${pkg.part === 'deployed' ? 'flows' : 'packages'}/${pkg.slug}`;
      const names = [id, pkg.slug, pkg.displayName, pkg.internalName].filter(Boolean).map(String);
      if (names.some((n) => n.toLowerCase() === low)) return true;
      if (keysOf(pkg).some((k) => k.toLowerCase() === low)) return true;
      if (glob && names.some((n) => glob.test(n))) return true;
      return false;
    });
    if (!hits.length) unmatched.push(term);
    for (const h of hits) chosen.set(h, true);
  }
  if (unmatched.length) {
    fail(`--only matched nothing for: ${unmatched.join(', ')}\n`
      + '     A term must name a package id, slug, flow name, internal name or contract key,\n'
      + `     a glob over those, or one of: ${Object.keys(ALIASES).join(', ')}.\n`
      + '     Refusing rather than exporting less than was asked for.');
  }
  /* Source order, so two runs of the same selection are byte-identical. */
  return { list: all.filter((p) => chosen.has(p)), complete: chosen.size === all.length, terms };
}
const fail = (msg) => { console.error(`\n  ✖  ${msg}\n`); process.exit(2); };

const model = await buildProvisioningModel();
const { packages, keysByFile, register, portalByInternalName, listsByGuid } = model;

/* ── what a reader looks a flow up BY ──────────────────────────────────────────────────
   A person arrives at this reference holding one of a few things: a flow name, a contract
   key, a list they saw in an audit, a connection that broke, or an action name out of a run
   history. Each of those is put in the haystack so the search finds the flow from any of
   them — the markdown index could only be searched by flow name, and only by the browser's
   own find-in-page, one page at a time. */
function haystack(pkg) {
  const terms = new Set([pkg.displayName, pkg.internalName, pkg.estate, pkg.family, pkg.file]);
  for (const c of keysByFile.get(pkg.file) || []) terms.add(c.key);
  for (const a of pkg.actions) {
    terms.add(a.name);
    terms.add(a.type);
    const conn = connectorOf(a);
    if (conn) { terms.add(conn.connectionName); terms.add(conn.operationId); }
    /* The SharePoint list a call targets is the single most common thing an operator is
       holding when they come here, and it is buried in an action's inputs — as a GUID. Nobody
       arrives holding a GUID. The tenant list index resolves it, so both the id and the name
       on the list find the flows that write to it; searching the markdown for
       `DGO_UserDirectory` finds nothing, because the string is not in it. */
    const t = a.inputs?.parameters?.table;
    if (typeof t === 'string') {
      terms.add(t);
      const known = listsByGuid.get(t.toLowerCase());
      if (known?.title) terms.add(known.title);
    }
    const site = a.inputs?.parameters?.dataset;
    if (typeof site === 'string') terms.add(site.split('/').pop());
  }
  return [...terms].filter(Boolean).map((t) => String(t)).join(' ').slice(0, 24000);
}

const contractKeysOf = (pkg) => (keysByFile.get(pkg.file) || []).map((c) => c.key).sort();

/* ── tier one: the list, the filters and the search ──────────────────────────────────── */

/* THE KEY IS THE DIRECTORY AND THE SLUG, NEVER THE SLUG ALONE.
   `Portal_UPLOAD_ECM_DOCS` is two packages — the deployed flow (33 actions) and the clipboard
   scope built for it (49) — and the model deliberately lets them share a slug, because it
   scopes slugs per output directory and they land in different ones. Keyed by slug alone, the
   second one read silently replaced the first, and the console showed one flow's configuration
   under the other's name. In a provisioning reference that is the worst available kind of
   wrong: it does not look like an error. */
const idOf = (pkg) => `${pkg.part === 'deployed' ? 'flows' : 'packages'}/${pkg.slug}`;

if (onlyArg && check) fail('--only and --check are contradictory: --check polices the committed data, which is always the whole estate.');
if (onlyArg && !standalone) fail('--only writes a single file only. Add --standalone.');

/* Both surfaces. The internal register names 20 contract keys; the seven portal endpoints are
   named elsewhere and reach a package through its internal name. Selecting by key has to see
   both, or `--only=SUBMISSION` refuses a flow that plainly serves SUBMISSION. */
const selectableKeys = (pkg) => {
  const keys = contractKeysOf(pkg);
  const portal = pkg.internalName ? portalByInternalName.get(pkg.internalName)?.key : null;
  return portal ? [...keys, portal] : keys;
};

const selection = selectPackages(packages, selectableKeys);
const selected = selection.list;

/* EVERY COUNT BELOW IS OVER THE SELECTION, NOT THE ESTATE.
   A one-flow export whose header reads "77 deployed flows" is worse than no header: it is a
   document that misdescribes itself, which is the whole failure class this reference exists
   to close. The selection is also recorded, so the page can say what it is. */
const index = selected.map((pkg) => ({
  id: idOf(pkg),
  slug: pkg.slug,
  dir: pkg.part === 'deployed' ? 'flows' : 'packages',
  name: pkg.displayName || pkg.file.split('/').pop(),
  internalName: pkg.internalName,
  estate: pkg.estate,
  estateBasis: pkg.estateBasis,
  family: FAMILY[pkg.family]?.label ?? pkg.family,
  deployed: pkg.part === 'deployed',
  triggerType: pkg.trigger?.type ?? null,
  method: pkg.trigger?.method ?? null,
  auth: pkg.trigger?.triggerAuthenticationType ?? null,
  actionCount: pkg.actions.length,
  responseCount: pkg.actions.filter((a) => a.type === 'Response').length,
  contractKeys: contractKeysOf(pkg),
  page: pkg.page,
  file: pkg.file,
  q: haystack(pkg).toLowerCase(),
}));

/* ── tier two: every configured value ─────────────────────────────────────────────────
   `raw` and `metadata` are dropped. `raw` is the source object the other fields were read
   out of — carrying it doubles the payload to say the same thing twice — and
   `operationMetadataId` is a designer bookkeeping GUID that no page prints. Everything §13
   of a flow page renders is here, and nothing it does not. */
const detail = {};
for (const pkg of selected) {
  detail[idOf(pkg)] = {
    identity: {
      displayName: pkg.displayName,
      internalName: pkg.internalName,
      workflowId: pkg.workflowId,
      environmentName: pkg.environmentName,
      fullResourceId: pkg.fullResourceId,
      estate: pkg.estate,
      estateBasis: pkg.estateBasis,
      family: FAMILY[pkg.family]?.label ?? pkg.family,
      familyNote: FAMILY[pkg.family]?.note ?? null,
      exportedAtUtc: pkg.exportedAtUtc,
      exportedBy: pkg.exportedBy,
      file: pkg.file,
      page: pkg.page,
      contractKeys: contractKeysOf(pkg),
      portalEndpoint: pkg.internalName ? (portalByInternalName.get(pkg.internalName)?.key ?? null) : null,
    },
    envelope: {
      schemaUri: pkg.schemaUri,
      contentVersion: pkg.contentVersion,
      description: pkg.definitionDescription,
      outputs: redactDeep(pkg.outputs),
      actionCount: pkg.actions.length,
    },
    parameters: redactDeep(pkg.parameters),
    trigger: pkg.trigger ? redactDeep(pkg.trigger) : null,
    connections: connectionRows(pkg),
    sharepoint: sharepointRows(pkg),
    http: httpRows(pkg),
    actions: pkg.actions.map((a) => {
      const conn = connectorOf(a);
      const row = {
        path: a.path,
        name: a.name,
        type: a.type,
        depth: a.depth,
        kind: a.kind,
        description: a.description,
        runAfter: a.runAfter,
        isFirst: a.isFirst,
        isCatch: a.isCatch,
      };
      if (conn) row.connector = { connectionName: conn.connectionName, apiId: conn.apiId, operationId: conn.operationId };
      if (a.inputs !== undefined) row.inputs = redactDeep(a.inputs);
      if (a.expression !== undefined) row.expression = redactDeep(a.expression);
      if (a.foreach !== undefined) row.foreach = redactDeep(a.foreach);
      if (notEmpty(a.runtimeConfiguration)) row.runtimeConfiguration = redactDeep(a.runtimeConfiguration);
      if (notEmpty(a.trackedProperties)) row.trackedProperties = redactDeep(a.trackedProperties);
      if (a.operationOptions) row.operationOptions = a.operationOptions;
      return row;
    }),
  };
}

function notEmpty(v) {
  if (v === undefined || v === null) return false;
  if (Array.isArray(v)) return v.length > 0;
  if (typeof v === 'object') return Object.keys(v).length > 0;
  return true;
}

/**
 * §10 — one row per SharePoint connector call, with the GUID resolved.
 *
 * `table` is configured as a list GUID and nobody arrives holding one, so the tenant list
 * index names it. Detection reads the api id, the connection name AND the reference name,
 * because a package can carry any of the three — the same test the markdown applies, written
 * once here so a row cannot appear on one and not the other.
 */
function sharepointRows(pkg) {
  const rows = [];
  for (const a of pkg.actions) {
    const c = connectorOf(a);
    const hostText = `${c?.apiId || ''} ${c?.connectionName || ''} ${c?.connectionReferenceName || ''}`;
    if (!/sharepointonline/i.test(hostText)) continue;
    const params = a.inputs?.parameters || {};
    const tbl = params.table ?? null;
    const hit = typeof tbl === 'string' ? listsByGuid.get(tbl.toLowerCase()) : null;
    rows.push({
      path: a.path,
      operationId: c?.operationId ?? null,
      connection: c?.connectionName ?? null,
      dataset: params.dataset ?? null,
      table: tbl,
      resolved: hit ? `${hit.title} — ${hit.site}` : null,
    });
  }
  return rows;
}

/** §11 — raw HTTP, webhooks included. */
function httpRows(pkg) {
  return pkg.actions
    .filter((a) => a.type === 'Http' || a.type === 'HttpWebhook')
    .map((a) => ({
      path: a.path,
      method: a.inputs?.method ?? null,
      uri: a.inputs?.uri ?? null,
      headers: a.inputs?.headers ?? null,
      queries: a.inputs?.queries ?? null,
      body: Object.prototype.hasOwnProperty.call(a.inputs || {}, 'body') ? redactDeep(a.inputs.body) : undefined,
      authentication: a.inputs?.authentication ?? null,
      retryPolicy: a.runtimeConfiguration?.retryPolicy ?? null,
    }));
}

/** Which connection each action is bound to, counted by operation — §4 of a flow page. */
function connectionRows(pkg) {
  const byConn = new Map();
  for (const a of pkg.actions) {
    const c = connectorOf(a);
    if (!c) continue;
    const key = c.connectionName ?? c.apiId ?? '—';
    if (!byConn.has(key)) byConn.set(key, { connectionName: c.connectionName, apiId: c.apiId, operations: new Map() });
    const ops = byConn.get(key).operations;
    ops.set(c.operationId ?? '—', (ops.get(c.operationId ?? '—') ?? 0) + 1);
  }
  return [...byConn.values()].map((c) => ({
    connectionName: c.connectionName,
    apiId: c.apiId,
    operations: [...c.operations].map(([op, n]) => ({ op, n }))
      .sort((x, y) => y.n - x.n || byteCompare(String(x.op), String(y.op))),
  }));
}

/* ── totals, stated once so the interface never counts differently from the markdown ─── */
const deployed = selected.filter((p) => p.part === 'deployed');
const meta = {
  generatedBy: 'scripts/build-provisioning-console.mjs',
  model: 'scripts/lib/provisioning-model.mjs',
  markdown: `${OUT_DIR}/README.md`,
  selection: {
    complete: selection.complete,
    terms: selection.terms,
    /* What was left out, so a reader of a partial export knows there is more and where. */
    estateTotal: packages.length,
  },
  totals: {
    packages: selected.length,
    deployedFlows: deployed.length,
    otherPackages: packages.length - deployed.length,
    actions: selected.reduce((n, p) => n + p.actions.length, 0),
    deployedActions: deployed.reduce((n, p) => n + p.actions.length, 0),
    responses: deployed.reduce((n, p) => n + p.actions.filter((a) => a.type === 'Response').length, 0),
    withRequestSchema: deployed.filter((p) => p.trigger?.schema).length,
    withoutTriggerAuth: deployed.filter((p) => !p.trigger?.triggerAuthenticationType).length,
    internalContractKeys: selection.complete
      ? (register.contractKeys || []).length
      : new Set(selected.flatMap(contractKeysOf)).size,
  },
};

/* ── emit ─────────────────────────────────────────────────────────────────────────────
   A generated artefact carrying a signature would be a published bearer credential, and
   everything above has already been through `redactDeep`. Checked anyway, on the finished
   string, because "already redacted" is how the last one got in. */
const SIG = /sig=[A-Za-z0-9_-]{20,}/;

const banner = (what) => `/* GENERATED by scripts/build-provisioning-console.mjs — do not edit.\n   ${what}\n   Rebuild with: npm run provisioningconsole */\n`;

const emit = [
  [`${OUT_DIR}/provisioning-index.js`,
    `${banner(`${index.length} flow summaries and the search haystack. Loaded in the head.`)}window.DGO_PROVISIONING_INDEX = ${JSON.stringify({ meta, index }, null, 0)};\n`],
  [`${OUT_DIR}/provisioning-detail.js`,
    `${banner('Every configured value, action by action. Injected after first paint.')}window.DGO_PROVISIONING_DETAIL = ${JSON.stringify(detail, null, 0)};\n`],
];

for (const [rel, body] of emit) {
  if (SIG.test(body)) fail(`${rel} would carry a signature. Refusing to write it.`);
}

if (check) {
  let drifted = 0;
  for (const [rel, body] of emit) {
    let actual = null;
    try { actual = readFileSync(join(ROOT, rel), 'utf8'); } catch { /* missing */ }
    if (actual !== body) { console.error(`  ✖  ${rel} has drifted from the packages.`); drifted += 1; }
  }
  if (drifted) fail(`${drifted} generated file(s) differ from a rebuild. Run \`npm run provisioningconsole\`.`);
  console.log(`  ✅  Provisioning console data matches the packages — ${meta.totals.packages} packages, ${meta.totals.actions} actions.`);
  process.exit(0);
}

/* ── the single file ──────────────────────────────────────────────────────────────────
   The authored files are read rather than re-templated, so the export cannot drift from the
   console it is an export OF. Each external reference is replaced by the content it names —
   `<link>` and every `<script src>` — and nothing else is touched. */
const MIME = {
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon',
  '.woff2': 'font/woff2', '.woff': 'font/woff',
};

function buildStandalone() {
  const readOut = (name) => readFileSync(join(ROOT, `${OUT_DIR}/${name}`), 'utf8');
  const inline = (text) => `\n${text.replace(/<\/script>/gi, '<\\/script>')}\n`;
  const bodyOf = new Map(emit.map(([rel, text]) => [rel.split('/').pop(), text]));

  /* Everything else the page pulls in — the brand kit's stylesheet, its script, the mark and
     the lockups — is folded in generically rather than by name. The five files this started
     with were hardcoded, and the first thing upstream added (brand/) broke the export. The
     refusal at the bottom is what caught that, and this is what stops it recurring: anything
     local becomes a <style>, a <script>, or a data: URI, whatever it is called. */
  const swallowLocal = (html) => html
    .replace(/<link[^>]*rel="stylesheet"[^>]*href="((?!https?:|data:|\/\/)[^"]+)"[^>]*>/g,
      (whole, href) => `<style>${readOut(href)}</style>`)
    .replace(/<script src="((?!https?:|data:|\/\/)[^"]+)"><\/script>/g,
      (whole, src) => `<script>${inline(readOut(src))}</script>`)
    .replace(/(?:src|href)="((?!https?:|data:|#|\/\/)[^"]+)"/g, (whole, ref) => {
      const ext = ref.slice(ref.lastIndexOf('.')).toLowerCase();
      const type = MIME[ext];
      if (!type) return whole;                 /* left for the refusal below to report */
      const bytes = readFileSync(join(ROOT, OUT_DIR, ref));
      const attr = whole.slice(0, whole.indexOf('='));
      return `${attr}="data:${type};base64,${bytes.toString('base64')}"`;
    });

  let out = readOut('index.html')
    .replace('<link rel="stylesheet" href="console.css">',
      `<style>${readOut('console.css')}</style>`)
    .replace('<script src="provisioning-index.js"></script>',
      `<script>window.DGO_PROVISIONING_STANDALONE = true;</script>\n<script>${inline(bodyOf.get('provisioning-index.js'))}</script>`)
    /* The detail tier moves INTO the head here. The split exists to keep 6 MB off the first
       paint of a page loading five files over a filesystem; in one file there is nothing to
       defer to, and console.js takes the already-present global without injecting anything. */
    .replace('<script src="console.js"></script>',
      `<script>${inline(bodyOf.get('provisioning-detail.js'))}</script>\n<script>${inline(readOut('console.js'))}</script>`)
    /* The noscript block sends a reader to the markdown beside the page. There is nothing
       beside this one, so it says where the markdown lives instead of linking at it. */
    .replace(/<noscript>[\s\S]*?<\/noscript>/,
      ['<noscript>',
       '  <div style="max-width:60ch;margin:3rem auto;padding:1.5rem;border:1px solid #ccc;border-radius:10px">',
       '    <h1 style="font-size:1.2rem">This console needs scripting</h1>',
       '    <p>This is a single-file export and everything it shows is inside it, but it needs',
       '    JavaScript to render. With scripting off, read the markdown reference instead:',
       '    <code>docs/folio-Master-Flows-and-Endpoints/provisioning/</code> in the repository, which needs nothing at all.</p>',
       '    <p>Both are generated from the same model, so neither can say something the other cannot.</p>',
       '  </div>',
       '</noscript>'].join('\n'))
    .replace('<title>DGO — Provisioning console</title>',
      '<title>DGO — Provisioning console</title>\n<!-- Single-file export. Built by `npm run provisioningconsole:one`\n     from docs/folio-Master-Flows-and-Endpoints/provisioning/. Not committed; rebuild rather than edit. -->');

  out = swallowLocal(out);

  for (const left of out.match(/(?:src|href)="(?!data:|#)[^"]+"/g) || []) {
    fail(`the single file still references ${left} — it would not open on its own.`);
  }
  return out;
}

let bytes = 0;
/* A narrowed run writes NO folder data. docs/folio-Master-Flows-and-Endpoints/provisioning/ is the whole estate by
   definition, and a `--only` run that overwrote it would leave the committed console showing
   one flow while still calling itself the reference. */
if (!onlyArg) {
  for (const [rel, body] of emit) {
    const abs = join(ROOT, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
    bytes += Buffer.byteLength(body);
    console.log(`  ${rel}  ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`);
  }
  console.log(`\n  ${meta.totals.packages} packages · ${meta.totals.deployedFlows} deployed flows · ${meta.totals.actions} actions · ${(bytes / 1024 / 1024).toFixed(2)} MB total`);
} else {
  console.log(`  selection: ${selection.terms.join(', ')}`);
  console.log(`  ${meta.totals.packages} of ${packages.length} packages · ${meta.totals.actions} actions`);
  for (const r of index) console.log(`    ${r.id}${r.contractKeys.length ? `  (${r.contractKeys.join(', ')})` : ''}`);
}

if (standalone) {
  const one = buildStandalone();
  if (SIG.test(one)) fail('the single file would carry a signature. Refusing to write it.');
  /* Named after what is in it. Three selections written to one filename is how somebody ends
     up mailing the wrong one. */
  const stem = selection.complete
    ? 'provisioning-console'
    : `provisioning-console-${selection.terms.join('+')
        .replace(/[^A-Za-z0-9._+-]+/g, '-')
        .replace(/-{2,}/g, '-')          /* `cg-*` sanitised to `cg--`; one dash is enough */
        .replace(/^[-.]+|[-.]+$/g, '')
        .slice(0, 60)}`;
  const target = process.env.DGO_STANDALONE_OUT || join(ROOT, `dist-console/${stem}.html`);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, one);
  console.log(`\n  single file: ${target}  ${(Buffer.byteLength(one) / 1024 / 1024).toFixed(2)} MB`);
}
