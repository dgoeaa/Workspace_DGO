/**
 * The brand kit, as text a build can write into a page or a package.
 *
 * One source, `styles/dgo-design-system/`, reaches every output in one of two portable forms:
 *
 *   EMBEDDED  a single file that must open on its own. `brandKitBlock()` returns the tokens, the
 *             kit's CSS and (optionally) its script as inline <style>/<script>, fenced by
 *             <!-- brand:kit:start --> … <!-- brand:kit:end --> so `npm run brand:sync` can
 *             replace the block in place when the design system changes.
 *   PACKAGED  a folder of files that ships together. `packageFiles()` returns the files for its
 *             brand/ folder: brand.css (tokens + kit), brand.js, and the logo masters.
 *
 * Either way the output references nothing outside itself: no CDN, no font service, no path
 * back into the repository. `test:brand` compares every copy with what this module produces now.
 */

import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brandTokensCss } from './brand-tokens.mjs';

export const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const DS = 'styles/dgo-design-system';
const read = (rel, enc = 'utf8') => readFileSync(join(ROOT, rel), enc);

export const KIT_START = '<!-- brand:kit:start';
export const KIT_END = '<!-- brand:kit:end -->';

/** The logo masters. Keys are what callers ask for. */
/* The digital lockups are transparent cut-outs, so they sit on any surface. The package's
   horizontal and stacked white-outs carry their own opaque green (rgb 0 78 39, not Deep Green)
   and are for fixed-background use such as print; on a Deep Green header they show as a box. */
export const LOGOS = Object.freeze({
  white: 'nitda-lockup-digital-white.png',     // on Deep Green and dark surfaces
  colour: 'nitda-lockup-digital-colour.png',   // on white and light surfaces
  symbol: 'nitda-symbol-infoweb.png',
  dgo: '../dgo/dgo-mark.svg',                  // the DGO Digital Ops atomic-O mark (internal surfaces)
});
const LOGO_SIZE = { white: [544, 254], colour: [572, 260], symbol: [82, 82], dgo: [56, 56] };
const MIME = { jpeg: 'image/jpeg', jpg: 'image/jpeg', png: 'image/png', svg: 'image/svg+xml' };

export function kitCss() { return read(`${DS}/kit/brand-kit.css`).trim(); }
export function kitJs() { return read(`${DS}/kit/brand-kit.js`).trim(); }
export function platformCss() { return read(`${DS}/kit/brand-platform.css`).trim(); }

/** Tokens, the kit, and the platform chrome with the DGO lockup: everything a page needs. */
export function brandCss() {
  return `${brandTokensCss()}\n\n${kitCss()}\n\n${platformCss()}\n`;
}

/** A logo master as a data: URI, for a page that must carry it inside itself. */
export function logoDataUri(which = 'white') {
  const file = LOGOS[which];
  if (!file) throw new Error(`unknown logo "${which}"; one of ${Object.keys(LOGOS).join(', ')}`);
  const ext = file.split('.').pop();
  return `data:${MIME[ext]};base64,${read(`${DS}/brand/nitda/${file}`, null).toString('base64')}`;
}

/** An <img> of the logo, embedded. `alt` is the agency's full name, as the Brand Manual requires. */
export function logoImg(which = 'white', { className = 'bk-logo', width = 128 } = {}) {
  const [w, h] = LOGO_SIZE[which];
  return `<img class="${className}" src="${logoDataUri(which)}" alt="National Information Technology Development Agency" width="${w}" height="${h}" style="width:${width}px;height:auto">`;
}

/**
 * The embedded block. `script: false` for a page that needs the look but no behaviour (a printed
 * report, an email preview); the default carries both.
 */
export function brandKitBlock({ script = true } = {}) {
  /* The fence is found by text search, so the kit must never contain it: a marker quoted in a
     comment would end the block early on the next sync and truncate every page carrying it. */
  for (const [name, text] of [['brand-kit.css', kitCss()], ['brand-kit.js', kitJs()], ['brand-platform.css', platformCss()]]) {
    if (text.includes('brand:kit:')) throw new Error(`${DS}/kit/${name} contains the text "brand:kit:"; reword it`);
  }
  const opts = script ? '' : ' css-only';
  const js = script ? `\n<script data-brand-kit>\n${kitJs()}\n</script>` : '';
  return `${KIT_START}${opts} -->
<!-- Generated by \`npm run brand:sync\` from styles/dgo-design-system/. Do not edit inside this block. -->
<style data-brand-kit>
${brandCss()}</style>${js}
${KIT_END}`;
}

/** Replace the fenced block in a page, keeping the options its start marker declares. */
export function refreshBlock(html) {
  const a = html.indexOf(KIT_START);
  if (a < 0) return null;
  const b = html.indexOf(KIT_END, a);
  if (b < 0) throw new Error('brand:kit:start without brand:kit:end');
  const head = html.slice(a, html.indexOf('-->', a));
  const block = brandKitBlock({ script: !/\bcss-only\b/.test(head) });
  return html.slice(0, a) + block + html.slice(b + KIT_END.length);
}

/**
 * Point every logo slot in a single-file page at the current master, embedded. A slot is any
 * element carrying data-bk-logo="white|colour|symbol|dgo": an <img> gets its src, a <link rel=icon>
 * its href. Returns the page unchanged when it has no slots.
 */
export function refreshLogos(html) {
  return html.replace(/<(img|link)\b[^>]*\bdata-bk-logo="(white|colour|symbol|dgo)"[^>]*>/g, (tag, el, which) => {
    const attr = el === 'img' ? 'src' : 'href';
    const uri = logoDataUri(which);
    return new RegExp(`\\s${attr}="[^"]*"`).test(tag)
      ? tag.replace(new RegExp(`(\\s${attr}=)"[^"]*"`), `$1"${uri}"`)
      : tag.replace(/\s*\/?>$/, ` ${attr}="${uri}">`);
  });
}

/**
 * The DGO Digital Ops lockup, as markup (styles: kit/brand-platform.css). Built from text and
 * geometry so it is crisp at any size and never clips when a face is missing. `endorsed` adds
 * "An initiative of NITDA" for a surface that does not also show the NITDA logo.
 */
export function subLockup({ endorsed = false } = {}) {
  return '<span class="bk-sub__word" aria-hidden="true">DG<svg class="bk-sub__o" viewBox="0 0 56 56" aria-hidden="true" focusable="false">'
    + '<circle class="ring" cx="28" cy="28" r="20"/><circle class="dot" cx="28" cy="28" r="6.5"/></svg></span>'
    + '<span class="bk-sub__name" aria-hidden="true"><span>Digital</span><span>Ops</span>'
    + (endorsed ? '<span class="bk-sub__endorse">An initiative of NITDA</span>' : '') + '</span>'
    + '<span class="bk-sub__sr">DGO Digital Ops' + (endorsed ? ', an initiative of NITDA' : '') + '</span>';
}

/**
 * Fill every sub-brand slot — <span … data-bk-sub[="endorsed"]>…</span> — with the current
 * lockup. The slot's own attributes (class, size modifiers) are kept.
 */
export function refreshSubs(html) {
  return html.replace(/(<span\b[^>]*\bdata-bk-sub(?:="(endorsed)?")?[^>]*>)[\s\S]*?<!--\/bk-sub-->/g,
    (all, open, endorsed) => `${open}${subLockup({ endorsed: endorsed === 'endorsed' })}<!--/bk-sub-->`);
}

/** The files a package's brand/ folder carries, as [relative path, Buffer|string]. */
export function packageFiles({ logos = ['white', 'colour', 'symbol', 'dgo'] } = {}) {
  const files = [
    ['brand.css', `/* Generated by \`npm run brand:sync\` from styles/dgo-design-system/. Do not edit. */\n\n${brandCss()}`],
    ['brand.js', `/* Generated by \`npm run brand:sync\` from styles/dgo-design-system/kit/brand-kit.js. Do not edit. */\n${kitJs()}\n`],
  ];
  for (const k of logos) files.push([LOGOS[k].split('/').pop(), read(`${DS}/brand/nitda/${LOGOS[k]}`, null)]);
  return files;
}
