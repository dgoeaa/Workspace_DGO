writeOrCheck('docs/deployment/sharepoint/PORTAL_DATA_CONTRACT.md', `${out.join('\n')}\n`);

/* ------------------------------------------------- flow structures */

out.length = 0;

const deployedDir = join(ROOT, 'docs/reference/flow-contracts/deployed');
const flows = new Map();
for (const file of walk(deployedDir)) {
  let doc;
  try { doc = JSON.parse(readFileSync(file, 'utf8').replace(/^﻿/, '')); } catch { continue; }
  if (!isFlowDocument(doc)) continue;
  const id = identity(doc);
  if (id.displayName) flows.set(id.displayName, { id, def: definitionRoot(doc) });
}

/** Render a definition as an indented tree, marking branches and run order. */
function tree(actions, depth = 0, lines = []) {
  const order = Object.entries(actions || {});
  for (const [name, action] of order) {
    const after = Object.keys(action.runAfter || {});
    const when = after.length ? `after ${after.join(', ')}` : 'first';
    lines.push(`${'  '.repeat(depth)}- ${name} [${action.type}] — ${when}`);
    if (action.actions) tree(action.actions, depth + 1, lines);
    if (action.else?.actions) {
      lines.push(`${'  '.repeat(depth + 1)}ELSE`);
      tree(action.else.actions, depth + 2, lines);
    }
    if (action.default?.actions) {
      lines.push(`${'  '.repeat(depth + 1)}DEFAULT`);
      tree(action.default.actions, depth + 2, lines);
    }
    for (const [cn, branch] of Object.entries(action.cases || {})) {
      lines.push(`${'  '.repeat(depth + 1)}CASE ${cn} = ${JSON.stringify(branch.case)}`);
      tree(branch.actions, depth + 2, lines);
    }
  }
  return lines;
}

emit('# Flow structures, end to end');
emit();
emit('> Generated by `scripts/build-estate-docs.mjs`. Do not edit by hand.');
emit();
emit('For each portal flow: what is deployed in the tenant today, and every change its');
emit('remediation applies. The changes are read out of the artifacts, which are the same source');
emit('the patcher and the operator worksheets are generated from, so this page cannot disagree');
emit('with what actually gets applied.');
emit();

const conformance = new Map(
  (standard.portalFlows || []).map((f) => [f, null]));

emit('## Coverage at a glance');
emit();
emit('| Endpoint | Flows | Required operations | Standard items | Visit |');
emit('|---|---|---|---|---|');
for (const e of wiring.endpoints) {
  /* An artifact may serve two endpoints — visit 1 covers VERIFY and VERIFY_CONFIRM, visit 5
     covers UPLOAD and SUPPORT — so match on membership rather than on equality. */
  const rem = REMEDIATIONS.find((r) => String(r.doc.endpoint).split(/,\s*/).includes(e.endpoint));
  emit(`| ${e.endpoint} | ${e.deployedFlowCandidates.map((f) => `\`${f}\``).join(', ')} | ${e.requiredOperations.length} | ${rem ? (rem.doc.standardConformance?.perFlow || []).reduce((n, p) => n + (p.missing || []).length, 0) : '—'} | ${rem ? rem.doc.visit : '—'} |`);
}
emit();

for (const { id, doc } of REMEDIATIONS) {
  emit(`## Visit ${doc.visit} — ${id}`);
  emit();
  emit(`**Endpoint:** ${doc.endpoint}  ·  **Closes:** ${doc.closes}`);
  emit();

  const flowNames = [...new Set([
    ...Object.keys(doc.actions || {}).map((k) => k.split(' / ')[0]),
    ...(doc.newActionsRequired || []).map((a) => a.flow).filter((f) => f && f !== 'BOTH'),
    ...(doc.standardConformance?.perFlow || []).map((p) => p.flow),
  ])];

  for (const flowName of flowNames) {
    const deployed = flows.get(flowName);
    emit(`### \`${flowName}\``);
    emit();
    if (!deployed) {
      emit('_No export of this flow is in the repository, so its current structure cannot be shown._');
      emit();
      continue;
    }
    emit(`Internal name \`${deployed.id.internalName}\`.`);
    emit();

    const conf = (doc.standardConformance?.perFlow || []).find((p) => p.flow === flowName);
    if (conf) {
      emit(`**Build standard:** ${conf.conformanceBefore} before.`
        + (conf.conforms ? ' Already conforms — nothing to add.'
          : ` Missing ${conf.missing.map((m) => `\`${m.check}\``).join(', ')}.`));
      emit();
    }

    const repoints = Object.entries(doc.actions || {})
      .filter(([k]) => k.startsWith(`${flowName} / `));
    if (repoints.length) {
      emit('**Actions repointed to the portal estate**');
      emit();
      emit('| Action | Path | New list |');
      emit('|---|---|---|');
      for (const [k, spec] of repoints) {
        const table = spec.replaceParametersWith?.table;
        const listTitle = fieldSpec.lists.find((l) => l.listGuid === table)?.listTitle || table;
        emit(`| \`${k.split(' / ')[1]}\` | \`${spec.path}\` | ${listTitle} |`);
      }
      emit();
    }

    const adds = (doc.newActionsRequired || []).filter((a) => a.flow === flowName || a.flow === 'BOTH');
    if (adds.length) {
      emit('**Actions added**');
      emit();
      emit('| Action | Operation | List | Where |');
      emit('|---|---|---|---|');
      for (const a of adds) {
        emit(`| \`${a.name}\` | ${a.operation || a.type} | ${a.list || '—'} | ${a.place ? `\`${a.place.parent}\`${a.place.first ? ', first' : `, after \`${a.place.after}\``}` : (a.where || '_not yet placed_')} |`);
      }
      emit();
    }

    const gate = (doc.rateLimitGate?.perFlow || []).find((g) => g.flow === flowName);
    if (gate) {
      emit(`**Rate-limit gate** — ${gate.limitPerHour}/hour per source, ${doc.rateLimitGate.window}.`);
      emit(`Refusal: ${doc.rateLimitGate.refusal}.`);
      emit();
      emit(`The Switch is repointed from \`${gate.repoint.expressionFrom}\` to \`${gate.repoint.expressionTo}\`,`);
      emit(`and a case \`${gate.add.find((a) => a.type === 'SwitchCase')?.caseValue}\` returns the refusal through the standard envelope.`);
      emit();
    }

    if (doc.codeComparison && doc.codeComparison.flow === flowName) {
      emit('**Code comparison (D9)**');
      emit();
      emit(doc.codeComparison.problem);
      emit();
      emit(`\`${doc.codeComparison.add.name}\` is added at \`${doc.codeComparison.add.place.parent}\`, and`);
      emit(`${doc.codeComparison.add.moveIntoIfYes.map((n) => `\`${n}\``).join(', ')} move into its matching branch.`);
      emit();
    }

    emit('<details><summary>Deployed structure today</summary>');
    emit();
    emit('```');
    for (const line of tree(deployed.def.actions)) emit(line);
    emit('```');
    emit();
    emit('</details>');
    emit();
  }
}

emit('## What is not in any artifact');
emit();
emit('| | |');
emit('|---|---|');
emit('| `Portal Audit Events` | Provisioned, and no flow in the design reads or writes it. |');
emit('| CORS origin | Every portal flow returns `Access-Control-Allow-Origin: https://your-host`, a literal placeholder. A browser refuses the response from the real origin. |');
emit('| Seven third-party API keys | Redacted in this repository and still live in the tenant. Redaction is not rotation. |');
emit();

writeOrCheck('docs/deployment/sharepoint/FLOW_STRUCTURES.md', `${out.join('\n')}\n`);

/* ------------------------------------------------------------------ io */

function writeOrCheck(rel, text) {
  const path = join(ROOT, rel);
  const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (now === text) return;
  if (check) { stale.push(rel); return; }
  writeFileSync(path, text);
  console.log(`  wrote ${rel}`);
}

if (check) {
  if (stale.length) {
    console.error(`\n❌ stale — run: npm run estatedocs\n${stale.map((s) => `   ${s}`).join('\n')}\n`);
    process.exit(1);
  }
  console.log('\n✅ the estate documents match the specifications\n');
} else {
  console.log('');
}
