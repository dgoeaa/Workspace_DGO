const rows = (list, cols) => {
  if (!list || !list.length) return;
  emit(`| ${cols.join(' | ')} |`);
  emit(`|${cols.map(() => '---').join('|')}|`);
  for (const f of list) {
    const req = f.required === true ? '**yes**' : f.required === false ? 'no' : (f.required || '—');
    const persist = 'persistence' in f
      ? (f.persistence ? `\`${f.persistence}\`` : '_nowhere_') : '—';
    const extra = [f.const ? `const \`${f.const}\`` : '', f.enum ? `one of ${f.enum.map((e) => `\`${e}\``).join(', ')}` : '', f.note || ''].filter(Boolean).join(' · ');
    emit(`| \`${f.field}\` | ${f.type || '—'} | ${req} | ${persist} | ${extra} |`);
  }
  emit();
};

for (const c of contract.contracts) {
  emit('---');
  emit();
  emit(`## ${c.key}${c.appliesTo ? ` — applies to ${c.appliesTo}` : ''}`);
  emit();
  if (c.status) emit(`**${c.status}**`);
  if (c.specifiedBy) emit(`Specified by ${c.specifiedBy}.`);
  if (c.implementedBy) emit(`Implemented by: ${c.implementedBy}`);
  if (c.configuredBy) emit(`Configured by: ${c.configuredBy}`);
  if (c.status || c.specifiedBy || c.implementedBy) emit();
  if (c.purpose) { emit(c.purpose); emit(); }
  if (c.method) { emit(`\`${c.method}\` · ${c.transport}`); emit(); }

  if (c.request?.length) { emit('### Request'); emit(); rows(c.request, ['Field', 'Type', 'Required', 'Persisted to', 'Notes']); }
  if (c.derived?.length) { emit('### Written by the flow'); emit(); rows(c.derived, ['Value', 'Type', 'Required', 'Persisted to', 'Notes']); }
  if (c.response?.length) { emit('### Response'); emit(); rows(c.response, ['Field', 'Type', 'Required', 'Persisted to', 'Notes']); }

  if (c.limits) {
    emit('### Limits'); emit();
    emit('| Endpoint | Per hour per source |'); emit('|---|---|');
    for (const [k, v] of Object.entries(c.limits)) emit(`| ${k} | ${v} |`);
    emit();
  }
  if (c.statuses) {
    emit('### Status codes'); emit();
    emit('| Code | Meaning |'); emit('|---|---|');
    for (const [k, v] of Object.entries(c.statuses)) emit(`| \`${k}\` | ${v} |`);
    emit();
  }
  if (c.excludedFromProjection) {
    emit('### Never in the projection'); emit();
    for (const x of c.excludedFromProjection) emit(`- ${x}`);
    emit();
    emit('A field absent from this list is not thereby permitted — the projection is an allow-list.');
    emit();
  }
}

emit('---');
emit();
emit('## Cross-cutting');
emit();
for (const [k, v] of Object.entries(contract.crossCutting)) emit(`- **${k}** — ${v}`);
