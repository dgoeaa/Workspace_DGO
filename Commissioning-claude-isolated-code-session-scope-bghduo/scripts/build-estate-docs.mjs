emit('# Portal data contract');
emit();
emit('> Generated by `scripts/build-estate-docs.mjs` from');
emit('> [`portal-data-contract.json`](./portal-data-contract.json). Do not edit by hand.');
emit('> `npm test` fails if it drifts, or if any target names a column that was never provisioned.');
emit();
emit(`**Version ${contract.contractVersion} · ${contract.status}**`);
emit();
emit(contract.purpose);
emit();
emit(`> **Precedence.** ${contract.precedence}`);
emit();
emit('## Derived from');
emit();
for (const d of contract.derivedFrom) emit(`- ${d}`);
emit();
emit('## Conventions');
emit();
for (const [k, v] of Object.entries(contract.conventions)) emit(`- **${k}** — ${v}`);
