#!/usr/bin/env node
/**
 * Generate the two reference documents that describe the estate: every SharePoint list the
 * portal and the governance site hold, and the structure of every flow that touches them.
 *
 * WHY GENERATED
 * Both documents restate facts that live in specifications and in exported definitions. A hand
 * written copy of either goes stale the first time a column is added or an action moves, and
 * this repository has already been bitten twice by transcribed measurements — the catch-scope
 * count and the per-visit cost table were both wrong because they had been copied rather than
 * read. So these are built, and `--check` fails if the committed copy has drifted.
 *
 * Usage:
 *   node scripts/build-estate-docs.mjs
 *   node scripts/build-estate-docs.mjs --check
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { walk, definitionRoot, identity, isFlowDocument } from './lib/flow-definition-reader.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const check = process.argv.includes('--check');
/* Declared here, not beside writeOrCheck: the function is called from the emit passes above
   that definition, and a `const` in the io section leaves this in its temporal dead zone until
   the first stale file is found — which is exactly the run that needs it. */
const stale = [];
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

const fieldSpec = read('docs/deployment/sharepoint/portal-field-spec.json');
const internalSpec = read('docs/reference/sharepoint-provisioning-spec.json');
const wiring = read('docs/deployment/sharepoint/portal-wiring.json');
const listMap = read('docs/reference/flow-list-map.json');
const standard = read('docs/deployment/sharepoint/flow-standard.json');
const httpFlowRegistry = read('docs/reference/http-flow-registry-spec.json');
const listIndex = read('docs/reference/sharepoint-list-index.json');

const REMEDIATIONS = ['01-otp-estate-split', '02-submission-registry-write',
  '03-status-registry-read', '04-intake-writeback', '05-upload-and-support']
  .map((id) => ({ id, doc: read(`docs/deployment/sharepoint/remediation/${id}.json`) }));

const out = [];
const emit = (s = '') => out.push(s);

/* ------------------------------------------------------------------ lists */

emit('# The SharePoint estate');
emit();
emit('> Generated by `scripts/build-estate-docs.mjs`. Do not edit by hand —');
emit('> run `npm run estatedocs`. `npm test` fails if this file has drifted from the specs.');
emit();
emit('Two estates share one tenant and never share a list. The portal estate is reached by');
emit('anonymous callers with no session; the governance estate is reached by authenticated NITDA');
emit('staff. Exactly one crossing between them is designed, and it is named at the end of this');
emit('page. A third set of lists — the HTTP flow registry — is specified but not yet built, and');
emit('is listed apart from both for that reason.');
emit();

const bySite = new Map();
for (const l of fieldSpec.lists) {
  if (!bySite.has(l.site)) bySite.set(l.site, []);
  bySite.get(l.site).push(l);
}

const totalFields = fieldSpec.lists.reduce((n, l) => n + l.fields.length, 0);
emit(`## Portal estate — ${fieldSpec.lists.length} lists, ${totalFields} provisioned columns`);
emit();
emit(`Specification: \`docs/deployment/sharepoint/portal-field-spec.json\` v${fieldSpec.specVersion}.`);
emit('Every list is addressed by GUID, never by title — a renamed list keeps its GUID and a');
emit('retitled one would otherwise silently become a different target.');
emit();

/* Which flows touch each list, read out of the generated map rather than asserted. */
const touchedBy = new Map();
for (const l of listMap.listsTouched || []) {
  if (l.listGuid) touchedBy.set(String(l.listGuid).toLowerCase(), l.touchedBy || []);
}

for (const [site, lists] of [...bySite.entries()].sort()) {
  emit(`### Site \`${site}\``);
  emit();
  emit(`\`${lists[0].siteUrl}\``);
  emit();
  for (const l of lists.sort((a, b) => a.listOrder - b.listOrder)) {
    emit(`#### ${l.listTitle}`);
    emit();
    emit(`| | |`);
    emit(`|---|---|`);
    emit(`| List GUID | \`${l.listGuid}\` |`);
    emit(`| Server-relative URL | \`${l.serverRelativeUrl}\` |`);
    emit(`| Estate | ${l.estate} |`);
    emit(`| Provisioned columns | ${l.fields.length} |`);
    const readers = touchedBy.get(String(l.listGuid).toLowerCase());
    /* The map records the file; a reader wants the flow. Strip the id and the suffix the
       exporter's filename convention adds. */
    const names = (readers || []).map((f) => String(f).replace(/__[0-9a-f-]{8,}__full_definition$/i, '').replace(/\.flow$/, ''));
    emit(`| Touched by | ${names.length ? [...new Set(names)].map((f) => `\`${f}\``).join(', ') : '— nothing yet'} |`);
    emit();
    if (l.fields.length) {
      emit('| Internal name | Designer label | Type | Required | Indexed |');
      emit('|---|---|---|---|---|');
      for (const f of l.fields) {
        emit(`| \`${f.internalName}\` | ${f.displayName} | ${f.fieldType} | ${f.required ? 'yes' : 'no'} | ${f.indexed ? 'yes' : 'no'} |`);
      }
      emit();
    }
  }
}

emit(`## Governance estate — ${internalSpec.lists.length} lists`);
emit();
emit('Specification: `docs/reference/sharepoint-provisioning-spec.json`. These serve the internal');
emit('DGO runtime. **No portal flow may read or write any of them** — that is the trust boundary,');
emit('and `npm run wiring` reports a violation as a boundary crossing.');
emit();
emit('| Order | List | Purpose | Fields | Required | Indexed | Seed rows |');
emit('|---|---|---|---|---|---|---|');
for (const l of internalSpec.lists.sort((a, b) => a.ListOrder - b.ListOrder)) {
  emit(`| ${l.ListOrder} | \`${l.ListTitle}\` | ${l.Purpose || l.Description || ''} | ${l.FieldCount} | ${l.RequiredFieldCount} | ${l.IndexedFieldCount} | ${l.SeedRecordCount} |`);
}
emit();
emit(`All ten sit on \`${internalSpec.lists[0].TargetSite}\`.`);
emit();

/* ------------------------------------------- http flow registry */

/* Kept out of the governance estate table above, and deliberately. Everything there is
   provisioned; every row of this is design-time. Merging them would put "defined" and "created"
   in one column and lose the only distinction that matters about these seven. */
const registryColumns = httpFlowRegistry.lists.reduce((n, l) => n + l.customFieldCount, 0);
emit(`## HTTP flow registry — ${httpFlowRegistry.lists.length} lists, ${registryColumns} columns, not yet provisioned`);
emit();
emit('Specification: `docs/reference/http-flow-registry-spec.json`, extracted from the workbook');
emit('beside it by `npm run httpflowregistry`. This is the flow-truth registry that the scope');
emit(`\`${httpFlowRegistry.registry.scopeNode}\``);
emit('creates: what every HTTP flow in the estate is, who owns it, what contract it honours, what');
emit('it depends on, who calls it, and how each run ended.');
emit();
emit('**Defined is not created.** Every execution-evidence value in the source workbook is');
emit('design-time — it records what the provisioning flow is configured to do, not what a run did.');
const capturedTitles = new Set(Object.values(listIndex.lists)
  .filter((l) => l.siteUrl === httpFlowRegistry.registry.targetSite).map((l) => l.title));
const builtAlready = httpFlowRegistry.lists.filter((l) => capturedTitles.has(l.listTitle));
if (builtAlready.length) {
  emit(`${builtAlready.length} of the ${httpFlowRegistry.lists.length} now appear in the ${listIndex.capturedUtc} capture of the site:`);
  emit(`${builtAlready.map((l) => `\`${l.listTitle}\``).join(', ')}. The rest are still specification only.`);
} else {
  emit(`None of the ${httpFlowRegistry.lists.length} appears in the ${listIndex.capturedUtc} capture of the site, and`);
  emit('`npm run test:httpflowregistry` holds that: it goes red the day a capture contains them.');
}
emit();
emit('| List | What it holds | Columns | Unique key | Views |');
emit('|---|---|---|---|---|');
for (const l of httpFlowRegistry.lists) {
  const views = httpFlowRegistry.views.filter((v) => v.listTitle === l.listTitle).map((v) => `\`${v.viewTitle}\``);
  emit(`| \`${l.listTitle}\` | ${l.description} | ${l.customFieldCount} | \`${l.uniqueKey}\` | ${views.length ? views.join(', ') : '—'} |`);
}
emit();
emit(`All ${httpFlowRegistry.lists.length} sit on \`${httpFlowRegistry.registry.targetSite}\`, under the`);
emit(`field group \`${httpFlowRegistry.registry.fieldGroup}\` — the same site the governance lists`);
emit(`already use. ${httpFlowRegistry.configSeeds.length} configuration seeds come with them, two of which restate the expected`);
emit('list and field counts so a run can check its own work. `CaptureRequestBody` and');
emit('`CaptureHeaders` are seeded false, and that is what keeps request payloads out of the ledger.');
emit();

emit('## Operational lists the portal flows use today');
emit();
emit('These are not part of the provisioned portal estate. The deployed flows still write to them,');
emit('and every remediation visit exists to move that traffic onto the lists above.');
emit();
emit('| List | Site | Why it appears |');
emit('|---|---|---|');
emit('| `NITDA_Central_Registry` | NEDMS | Where portal submissions land today. Existing rows stay until provisioning concludes. |');
emit('| `Global Tracking Queue` | NITDADGO-EAAACTIVITYTRACKING | Read by submission, upload, support and status flows. |');
emit('| `OTP_Transactions` | NITDADGO-EAAACTIVITYTRACKING | The internal sign-in challenge store. `Web - OTP Generate` and `Web - OTP Verify` belong here and are not portal flows. |');
emit();

emit('## The one designed crossing');
emit();
emit(`\`${wiring.bridge?.flow || 'ECM_DOCS_INTAKE'}\` reads \`${wiring.bridge?.list || 'Portal Registry'}\`.`);
emit('It is tenant-authenticated and read-only, and it is the only place the internal platform is');
emit('permitted to touch the portal estate.');
emit();

