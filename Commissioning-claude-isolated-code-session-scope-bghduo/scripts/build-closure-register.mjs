#!/usr/bin/env node
/**
 * The closure register — every item this estate has discharged, and on what evidence.
 *
 *   npm run closed
 *   npm run closed -- --check
 *
 * WHY THIS EXISTS
 *
 * Every instrument in this estate reports what is OUTSTANDING. npm run readiness counts open
 * items, npm run commission lists open obligations, CLOSURE_DISPOSITION.md dispositions the 22
 * open ones, OUTSTANDING.md totals 87 across five registers. Nothing enumerated what had been
 * CLOSED — so the 29 discharged items existed only as a subtraction, visible as a number and
 * nowhere as a record.
 *
 * That asymmetry is not cosmetic, and this repository has already paid for it twice. A closure
 * with no record is indistinguishable from an oversight: GOV-08 sat in openFindings for five days
 * carrying "RESOLVED IN THE TENANT", and CFG-2 spent eleven days telling operators to record
 * workflow ids that were already recorded. Both survived because the way to check a closure was to
 * go and re-derive it. When re-deriving is the only option, the cheap move is to re-raise the item,
 * and re-raising discharged work is the failure this whole baseline was corrected for.
 *
 * So: what closed, when, on whose authority, against what evidence — in one generated document,
 * derived from the same two registers the outstanding instruments read. If a closure is wrong, it
 * is now wrong in public.
 *
 * WHAT IT DOES NOT DO
 *
 * It does not close anything, and it cannot. Status lives in the registers; this reads them. An
 * item appears here because a register says it is closed, and the register says that because
 * someone recorded evidence — not because this document was generated.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const READINESS = 'docs/deployment/PRODUCTION_READINESS_REGISTER.json';
const GOVERNANCE = 'docs/reference/governance-estate-position.json';
const TARGET = 'docs/deployment/CLOSED.md';
const CHECK = process.argv.includes('--check');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

const reg = JSON.parse(read(READINESS));
const gov = existsSync(join(ROOT, GOVERNANCE))
  ? JSON.parse(read(GOVERNANCE)) : { openFindings: [], closedFindings: [] };

/* The three statuses that mean discharged, and what each one actually claims. Stated here rather
   than assumed, because they are NOT equivalent and a reader deciding whether to trust a closure
   needs to know which kind it is. */
const CLOSED_STATUS = {
  RESOLVED: 'The item\'s own resolution criteria are met, with the evidence named.',
  ACCEPTED: 'Known, reasoned, and deliberately not being changed. The requirement stands and cannot be met.',
  DISCHARGED_UNTRACKABLE: 'Done and evidenced once, and permanently unverifiable from this repository — the proof is a credential or a git-ignored file. A gate here will go on reporting it as outstanding forever.',
};

/* A date the closure states about itself. Never invented: an item whose record does not say when
   it closed is listed with the date withheld rather than given a plausible one. */
const dateFrom = (text) => (/\b(20\d{2}-\d{2}-\d{2})\b/.exec(text || '') || [])[1] || null;

const readinessClosed = reg.items
  .filter((i) => CLOSED_STATUS[i.status])
  .map((i) => ({
    id: i.id,
    title: i.title,
    status: i.status,
    owner: i.owner,
    why: (i.whyOpen || '').trim(),
    when: dateFrom(i.whyOpen) || dateFrom(JSON.stringify(i.evidence || [])),
    evidence: (i.evidence || []).map((e) => ({ type: e.type, ref: e.ref, states: e.states })),
  }));

const governanceClosed = (gov.closedFindings || []).map((f) => ({
  id: f.id,
  title: f.title,
  status: 'CLOSED',
  owner: f.owner || null,
  why: (f.status && f.status.length > (f.detail || '').length ? f.status : f.detail) || '',
  when: f.closedUtc || f.correctedUtc || null,
  tenant: f.tenantStatus || null,
  repository: f.repositoryStatus || null,
}));

const byStatus = {};
for (const i of readinessClosed) byStatus[i.status] = (byStatus[i.status] || 0) + 1;

const total = readinessClosed.length + governanceClosed.length;
const dated = [...readinessClosed, ...governanceClosed].filter((i) => i.when).length;

/* ------------------------------------------------------------------ *
 * Compose
 * ------------------------------------------------------------------ */

const esc = (s) => String(s || '').replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim();
const truncate = (s, n) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

let md = `# Closed — what this estate has discharged

**Generated by \`npm run closed\` from [\`PRODUCTION_READINESS_REGISTER.json\`](./PRODUCTION_READINESS_REGISTER.json)
and [\`governance-estate-position.json\`](../reference/governance-estate-position.json).**
Do not edit by hand — \`npm run test:closed\` fails on drift.

> **${total} items are closed.** ${readinessClosed.length} in the readiness register,
> ${governanceClosed.length} in the governance estate. ${dated} of them record the date they
> closed; the rest state the evidence without one, and no date has been invented for them here.

This is the counterpart to [\`OUTSTANDING.md\`](./OUTSTANDING.md). Every other instrument in this
estate reports what is left: \`npm run readiness\` counts open items, \`npm run commission\` lists
open obligations, \`CLOSURE_DISPOSITION.md\` dispositions the open ones. Nothing recorded what had
been discharged, so closed work existed as a subtraction and nowhere as a record — and a closure
with no record is indistinguishable from an oversight. **\`GOV-08\` spent five days filed as open
while reading "RESOLVED IN THE TENANT"; \`CFG-2\` spent eleven telling operators to record workflow
ids that were already recorded.** Both survived because checking a closure meant re-deriving it,
and the cheap move is to re-raise instead.

## What each closed status claims

| Status | Count | What it asserts |
|---|---:|---|
${Object.entries(CLOSED_STATUS).map(([s, meaning]) =>
  `| \`${s}\` | ${byStatus[s] || 0} | ${meaning} |`).join('\n')}
| governance \`CLOSED\` | ${governanceClosed.length} | Moved to \`closedFindings\` — resolved in the repository and in the tenant, or superseded by another finding. |

---

## Readiness register — ${readinessClosed.length} closed

| Item | Status | Closed | Discharged by | Why it closed |
|---|---|---|---|---|
${readinessClosed.map((i) =>
  `| **${i.id}** ${esc(truncate(i.title, 76))} | \`${i.status}\` | ${i.when || '_not stated_'} | ${esc(truncate(i.owner || '—', 44))} | ${esc(truncate(i.why, 230))} |`).join('\n')}

---

## Governance estate — ${governanceClosed.length} closed

| Finding | Closed | Why it closed |
|---|---|---|
${governanceClosed.map((f) =>
  `| **${f.id}** ${esc(truncate(f.title, 84))} | ${f.when || '_not stated_'} | ${esc(truncate(f.why, 300))} |`).join('\n')}

---

## The evidence behind each closure

Every file and command a closed item cites. A closure that cites nothing would appear here with an
empty list, which is why the list is printed rather than summarised.

${readinessClosed.map((i) => {
  /* A TABLE, NOT A BULLETED LIST, AND THE REASON IS THE RULE'S OWN.
     tests/single-source-of-truth.test.mjs holds that one document owns each executable
     instruction, and it reads a two-line window for an imperative near a script filename. A
     bulleted evidence list put `provision-sharepoint-fields.browser.js` one line above
     `designer-paste-builder.mjs` — and "designer-paste" contains "paste", so a citation read as
     an order to run it. The rule already excludes table cells, on exactly the ground this block
     stands on: a cell describes what a script IS; the step that runs it lives in the owning
     runbook. Rendering the citations as cells makes the document agree with the rule instead of
     asking the rule to make an exception for it. */
  const ev = i.evidence.length
    ? `| Cited | What it establishes |\n|---|---|\n${i.evidence.map((e) =>
      `| \`${e.ref}\`${e.type === 'command' ? ' _(command)_' : ''} | ${esc(truncate(e.states || '', 200))} |`).join('\n')}`
    : '_No evidence cited._';
  return `### ${i.id} · ${esc(i.title)}\n\n${ev}\n`;
}).join('\n')}

---

## How to check any of this

Every closure above is a claim about a register, and every register is read by a command. Where
this document and a command disagree, **the command governs**.

\`\`\`bash
npm run readiness     # the register's own tally, and whether it is pinned to this commit
npm run closed        # regenerate this document
npm run test:closure  # no document, and not the commissioning gate, presents a closed item as open
npm run outstanding   # the counterpart: what is still open, across all five registers
\`\`\`

A closure you believe is wrong is a register edit, not a document edit. Change the item's status
and evidence in the register it lives in, then regenerate.
`;

const abs = join(ROOT, TARGET);
if (CHECK) {
  const previous = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  if (previous === md) {
    console.log(`\n  ✅ ${TARGET} matches the registers — ${total} closed.\n`);
    process.exit(0);
  }
  console.error(`\n  ✖  ${TARGET} has drifted from the registers.`);
  console.error('     Run: npm run closed\n');
  process.exit(1);
}

writeFileSync(abs, md);
console.log('\nClosure register\n');
console.log(`  wrote ${TARGET}`);
for (const [s, n] of Object.entries(byStatus)) console.log(`  ${String(n).padStart(4)}  ${s}`);
console.log(`  ${String(governanceClosed.length).padStart(4)}  governance CLOSED`);
console.log(`  ${'─'.repeat(40)}`);
console.log(`  ${String(total).padStart(4)}  closed in total, ${dated} carrying a stated date\n`);
