#!/usr/bin/env node
/**
 * Generate the browser console patcher for `Web - OTP Verify` from the patched definition.
 *
 * WHY THIS EXISTS
 * `scripts/update-flow-definition.ps1` already does this job correctly, and its docstring records
 * why the obvious alternative does not work: legacy package import refuses to UPDATE a flow and
 * offers only "save as a new flow", which would mint a new trigger URL the portal does not hold.
 * So the definition has to go back over the same API the designer uses.
 *
 * What the PowerShell route costs the operator is a module install, an `Add-PowerAppsAccount`, a
 * git checkout and a Windows shell. This does the identical PATCH from the browser they are
 * already signed in to — the same shape as `provision-sharepoint-fields.browser.js`, which is how
 * every SharePoint column in this estate was provisioned.
 *
 * THE ONE HARD PART, AND HOW IT IS SOLVED
 * SharePoint REST authenticates on cookies, so a console fetch there is already signed in. The
 * Power Automate API does not: it takes an OAuth bearer token the SPA holds in memory. Rather
 * than guess at where a token is cached — which changes with every MSAL release — the script
 * hooks `fetch` and `XMLHttpRequest` and reads the Authorization header off a request the page
 * itself makes to `api.flow.microsoft.com`. The token is therefore correct by construction: it is
 * the token that host just accepted, at the audience that host requires, and the script reuses
 * the exact hostname it saw rather than assuming the global one.
 *
 * Generated, not hand-written, so the embedded definition cannot drift from the source of truth.
 *
 *   node scripts/build-otp-verify-browser-patch.mjs           # write
 *   node scripts/build-otp-verify-browser-patch.mjs --check    # fail if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = 'docs/deployment/power-automate-flows/otp-verify-patched-definition.json';
const OUT = 'scripts/apply-otp-verify-patch.browser.js';
const LIVE = 'docs/reference/flow-contracts/deployed/' +
  'Web - OTP Verify__3e201620-f1e8-4c17-a90a-4d95b94a24c2__full_definition.json';

const FLOW_ID = '3e201620-f1e8-4c17-a90a-4d95b94a24c2';
const ENVIRONMENT = 'Default-ca6a4b3f-9123-49bc-bcb9-27085ebbf1a1';

const read = (p) => JSON.parse(readFileSync(path.join(ROOT, p), 'utf8'));
const definition = read(SRC);
const live = read(LIVE).definition;

/* Guards on the payload itself. A generator that can embed anything is a generator that can embed
   a credential into a file that gets pasted into a browser and mailed around. */
const raw = JSON.stringify(definition);
for (const forbidden of ['sig=', 'Bearer ', 'AccessKey', 'SharedAccessSignature']) {
  if (raw.includes(forbidden)) throw new Error(`the definition carries ${forbidden} — refusing to embed it`);
}
if (!definition.triggers || Object.keys(definition.triggers).length !== 1) {
  throw new Error('the definition must carry exactly one trigger');
}
/* The trigger is the flow's identity: replacing it mints a new URL and the portal holds the old
   one. It is byte-identical in the patched definition for that reason, and this refuses to
   generate a patcher that would change it. */
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
if (!same(live.triggers, definition.triggers)) {
  throw new Error('the patched trigger differs from the live trigger — that would change the flow URL');
}

const topLive = Object.keys(live.actions);
const topNew = Object.keys(definition.actions);
const removed = topLive.filter((k) => !topNew.includes(k));
const added = topNew.filter((k) => !topLive.includes(k));
const changed = topNew.filter((k) => topLive.includes(k) && !same(live.actions[k], definition.actions[k]));

/* Markers the script checks against the tenant AFTER the write. Each is asserted here against the
   definition first, so a marker can never be checked for that the payload does not actually
   contain — a check that cannot fail is worse than no check. */
const MARKERS_PRESENT = ['Condition_Attempt_Cap', 'Get_items_OTP_Attempts', 'Update_item_Attempts', 'Title eq'];
const MARKERS_ABSENT = ['Scope_VERIFY_Complete_No_Trigger'];
for (const m of MARKERS_PRESENT) if (!raw.includes(m)) throw new Error(`marker missing from the definition: ${m}`);
for (const m of MARKERS_ABSENT) if (raw.includes(m)) throw new Error(`marker should be absent but is present: ${m}`);

const js = `/* =====================================================================================
   Web - OTP Verify — apply the patched definition, from the browser.
   GENERATED by scripts/build-otp-verify-browser-patch.mjs — do not edit by hand.

   HOW TO RUN IT
     1. Sign in to https://make.powerautomate.com and OPEN THE FLOW:
        My flows -> Web - OTP Verify. Be on the flow's own page.
     2. F12 -> Console. Paste this whole file. Press Enter.
     3. Press F5 to reload the flow page. That is what makes the portal fetch the
        definition, and this reads the answer as it goes past.
     4. It reports what it would change. NOTHING IS WRITTEN.
     5. To write it, type:   otpPatch.apply()

     otpPatch.status()   what it has found, and where
     otpPatch.dry()      run the read-only pass again (otpPatch.dry(5) to wait only 5s)
     otpPatch.rollback() put the previous definition back
     otpPatch.seen()     every authenticated endpoint it watched, for diagnosis

   IT GUESSES NOTHING. Earlier versions assumed a hostname, then assumed a URL path.
   Both were wrong on this tenant, because these flows are stored in Dataverse rather
   than at a ProcessSimple path. So this does not construct a URL at all: it watches
   the RESPONSES the portal receives and picks the one that actually contains this
   flow's definition. Whatever endpoint served the read is the endpoint it writes to,
   in whichever of the two shapes that endpoint uses.

   IT WILL NOT PRINT A TRIGGER URL, OR A TOKEN. Everything it prints is a count, a
   name, a hostname or a boolean, behind a guard that refuses anything carrying sig=
   or a bearer token.
   ===================================================================================== */

(() => {
  'use strict';

  const FLOW_ID = ${JSON.stringify(FLOW_ID)};
  const ENVIRONMENT = ${JSON.stringify(ENVIRONMENT)};
  const API_VERSION = '2016-11-01';

  /* Asserted against the live export at generation time, so these describe a real diff. */
  const EXPECTED = {
    topLevelBefore: ${topLive.length},
    topLevelAfter: ${topNew.length},
    removed: ${JSON.stringify(removed)},
    added: ${JSON.stringify(added)},
    changed: ${JSON.stringify(changed)},
    present: ${JSON.stringify(MARKERS_PRESENT)},
    absent: ${JSON.stringify(MARKERS_ABSENT)},
  };

  const DEFINITION = ${JSON.stringify(definition)};

  /* =================================================================================== */

  const T = { ok: 'color:#859900;font-weight:bold', bad: 'color:#dc322f;font-weight:bold',
              warn: 'color:#b58900', info: 'color:#268bd2', dim: 'color:#888' };

  const safe = (v) => {
    const s = typeof v === 'string' ? v : JSON.stringify(v);
    return /sig=|SharedAccessSignature|Bearer\\s|eyJ[A-Za-z0-9_-]{20}/i.test(s || '')
      ? '[redacted — carried a token]' : v;
  };
  const say = (msg, style) => (style ? console.log('%c' + safe(msg), style) : console.log(safe(msg)));

  const S = (window.__otpPatch = window.__otpPatch || {
    tokenByOrigin: new Map(),  /* origin -> the most recent Bearer the page sent it */
    seen: [],                  /* every authenticated endpoint watched, for diagnosis */
    found: null,               /* { url, origin, shape, rowId } — the endpoint that answered with the flow */
    envelope: null,            /* the document that carried it, kept so a write preserves its siblings */
    before: null,
  });

  /* ---- reading the answer, rather than guessing the question -------------------------
     Two storage shapes exist and this tenant decides which, not this file:

       ProcessSimple   { properties: { definition: { triggers, actions } } }
       Dataverse       a workflow row whose clientdata is a JSON STRING holding
                       { properties: { connectionReferences, definition } }

     classify() is the whole of the detection. It reads a response body and answers
     which shape it is, or nothing. A URL is never judged by its path. */
  const classify = (text) => {
    if (!text || text.length > 8e6 || !text.includes(FLOW_ID)) return null;
    let j; try { j = JSON.parse(text); } catch { return null; }
    const def = j && j.properties && j.properties.definition;
    if (def && def.actions && def.triggers) return { shape: 'processsimple', envelope: j };
    const rows = j && Array.isArray(j.value) ? j.value : [j];
    for (const r of rows) {
      if (!r || typeof r.clientdata !== 'string') continue;
      let cd; try { cd = JSON.parse(r.clientdata); } catch { continue; }
      const d = cd && cd.properties && cd.properties.definition;
      if (d && d.actions && d.triggers) {
        return { shape: 'dataverse', envelope: cd, rowId: r.workflowid || r.workflowidunique || null };
      }
    }
    return null;
  };

  const record = (url, auth, text) => {
    let u; try { u = new URL(url, location.href); } catch { return; }
    if (auth) S.tokenByOrigin.set(u.origin, auth);
    const where = u.origin + u.pathname;
    if (auth && !S.seen.includes(where)) S.seen.push(where);
    if (S.found || !text) return;
    const hit = classify(text);
    if (!hit) return;
    S.found = { url: u.href, origin: u.origin, shape: hit.shape, rowId: hit.rowId || null };
    S.envelope = hit.envelope;
    say('found the definition on ' + u.hostname + ' — ' + hit.shape + ' storage', T.ok);
  };

  if (!window.__otpPatchHooked) {
    window.__otpPatchHooked = true;
    const authOf = (input, init) => {
      try {
        let a = init && init.headers ? new Headers(init.headers).get('authorization') : null;
        if (!a && input && input.headers && typeof input.headers.get === 'function') a = input.headers.get('authorization');
        return a && /^Bearer /i.test(a) ? a : null;
      } catch { return null; }
    };
    const nativeFetch = window.fetch;
    window.fetch = function (input, init) {
      const url = typeof input === 'string' ? input : (input && input.url) || '';
      const auth = authOf(input, init);
      const p = nativeFetch.apply(this, arguments);
      if (auth) {
        p.then((res) => {
          if (!res || !res.ok || S.found) { record(url, auth, null); return; }
          /* clone() so the page still gets its body untouched. */
          res.clone().text().then((t) => record(url, auth, t)).catch(() => record(url, auth, null));
        }).catch(() => { /* a hook must never break the page it is watching */ });
      }
      return p;
    };
    const open = XMLHttpRequest.prototype.open;
    const setHeader = XMLHttpRequest.prototype.setRequestHeader;
    const send = XMLHttpRequest.prototype.send;
    XMLHttpRequest.prototype.open = function (m, url) { this.__otpUrl = url; return open.apply(this, arguments); };
    XMLHttpRequest.prototype.setRequestHeader = function (n, v) {
      try { if (String(n).toLowerCase() === 'authorization' && /^Bearer /i.test(v)) this.__otpAuth = v; } catch { /* as above */ }
      return setHeader.apply(this, arguments);
    };
    XMLHttpRequest.prototype.send = function () {
      if (this.__otpAuth) {
        this.addEventListener('load', () => {
          try { record(this.__otpUrl || '', this.__otpAuth, S.found ? null : this.responseText); }
          catch { /* a cross-origin or binary body simply is not the one */ }
        });
      }
      return send.apply(this, arguments);
    };
  }

  /* ---- talking to whatever answered -------------------------------------------------- */
  const call = async (method, url, body, extra) => {
    const origin = new URL(url).origin;
    const headers = Object.assign({
      Authorization: S.tokenByOrigin.get(origin),
      'Content-Type': 'application/json',
      Accept: 'application/json',
    }, extra || {});
    const res = await fetch(url, { method, headers, body: body ? JSON.stringify(body) : undefined });
    const text = await res.text();
    let json = null; try { json = JSON.parse(text); } catch { /* 204 and error pages are not JSON */ }
    return { res, json, text };
  };

  /** The single-row URL to write to. For Dataverse that is workflows(<id>), which the
      observed read may or may not have been addressed to. */
  const writeUrl = () => {
    if (S.found.shape !== 'dataverse') return S.found.url;
    if (S.found.rowId) return S.found.origin + '/api/data/v9.2/workflows(' + S.found.rowId + ')';
    return S.found.url;
  };

  const readDefinition = async () => {
    const { res, text } = await call('GET', S.found.url);
    if (!res.ok) { say('The read came back ' + res.status + '. Reload the flow page and run otpPatch.dry().', T.bad); return null; }
    const hit = classify(text);
    if (!hit) { say('That endpoint no longer returns this flow. Reload and run otpPatch.dry().', T.bad); return null; }
    S.envelope = hit.envelope;
    /* Only the definition is kept as the rollback. The envelope around it can carry a
       trigger URL, and that must not sit in a console variable. */
    return hit.envelope.properties.definition;
  };

  const writeDefinition = async (def) => {
    const url = writeUrl();
    if (S.found.shape === 'processsimple') {
      return call('PATCH', url, { properties: { definition: def } });
    }
    /* Dataverse: clientdata is one JSON string holding the definition AND the connection
       references. Replace the definition inside it and put the rest back untouched —
       rewriting the whole string from scratch would drop the connections. */
    const cd = JSON.parse(JSON.stringify(S.envelope));
    cd.properties.definition = def;
    return call('PATCH', url, { clientdata: JSON.stringify(cd) },
                { 'OData-Version': '4.0', 'OData-MaxVersion': '4.0', 'If-Match': '*' });
  };

  const waitForFlow = async (seconds) => {
    if (S.found) return true;
    say('Press F5 now to reload the flow page. Waiting up to ' + seconds + 's for the portal ' +
        'to fetch the definition…', T.warn);
    const until = Date.now() + seconds * 1000;
    while (!S.found && Date.now() < until) await new Promise((r) => setTimeout(r, 500));
    if (S.found) return true;
    say('Did not see it. Endpoints watched so far:', T.bad);
    for (const w of S.seen.slice(0, 40)) say('  ' + w, T.dim);
    if (!S.seen.length) say('  (none — is this the make.powerautomate.com tab?)', T.dim);
    say('Send me that list — hostnames and paths only, no tokens — and run otpPatch.dry() ' +
        'again after a reload.', T.warn);
    return false;
  };

  const report = (def) => {
    const top = Object.keys(def.actions);
    say('flow          Web - OTP Verify   (' + S.found.shape + ' storage on ' + new URL(S.found.url).hostname + ')');
    say('top-level     ' + top.length + ' action(s)');
    for (const m of EXPECTED.removed) {
      const there = top.includes(m);
      say((there ? '  present, will be removed: ' : '  already absent: ') + m, there ? T.warn : T.dim);
    }
    for (const m of EXPECTED.changed) {
      const differs = JSON.stringify(def.actions[m]) !== JSON.stringify(DEFINITION.actions[m]);
      say((differs ? '  differs, will be replaced: ' : '  already matches: ') + m, differs ? T.warn : T.dim);
    }
    return top;
  };

  const triggerMatches = (def) => JSON.stringify(def.triggers) === JSON.stringify(DEFINITION.triggers);

  /* The wait is a parameter so a short one can be asked for — otpPatch.dry(5) — rather than
     sitting through three minutes when you already know the portal has loaded the flow. */
  const dry = async (seconds = 180) => {
    if (!(await waitForFlow(seconds))) return;
    const def = await readDefinition();
    if (!def) return;
    S.before = def;
    report(def);
    const same = triggerMatches(def);
    say('trigger       ' + (same ? 'byte-identical — the URL does not change' : 'DIFFERS'), same ? T.ok : T.bad);
    say('────────────────────────────────────', T.dim);
    if (!same) {
      say('The live trigger is not the one this patch was built against. otpPatch.apply() will ' +
          'refuse: sending it would change the flow URL and the portal holds the current one. ' +
          'Send the flow name and this line — never the URL — and it will be rebuilt.', T.bad);
      return;
    }
    say('NOTHING WAS SENT. This was the read-only pass.', T.warn);
    say('To apply it, type:  otpPatch.apply()', T.info);
  };

  const apply = async (seconds = 180) => {
    if (!(await waitForFlow(seconds))) return;
    const def = await readDefinition();
    if (!def) return;
    S.before = def;
    const topBefore = report(def);
    if (!triggerMatches(def)) {
      say('Refusing: the live trigger differs from the one this patch was built against, and ' +
          'sending it would change the flow URL. Nothing sent.', T.bad);
      return;
    }
    say('rollback      otpPatch.rollback()', T.dim);
    say('sending…', T.info);
    const { res, json } = await writeDefinition(DEFINITION);
    if (!res.ok) {
      say('REFUSED — ' + res.status + ' ' + safe((json && json.error && json.error.message) || ('HTTP ' + res.status)), T.bad);
      say('The service validates the whole definition before it takes any of it, so the flow is ' +
          'unchanged. WorkflowOperationParametersExtraParameter would mean a SharePoint column ' +
          'the definition writes is missing from the list.', T.dim);
      return;
    }

    const after = await readDefinition();
    if (!after) { say('Written, but the read-back returned nothing. Open the flow in the designer.', T.bad); return; }
    const afterText = JSON.stringify(after);
    const topAfter = Object.keys(after.actions);

    let failures = 0;
    const check = (label, cond) => {
      if (cond) console.log('%c  ✅ ' + label, T.ok);
      else { failures++; console.log('%c  ❌ ' + label, T.bad); }
    };
    say('────────────────────────────────────', T.dim);
    say('Read back from the tenant:', T.info);
    check('top level holds ' + EXPECTED.topLevelAfter + ' action(s)', topAfter.length === EXPECTED.topLevelAfter);
    for (const m of EXPECTED.absent) check(m + ' is gone', !afterText.includes(m));
    for (const m of EXPECTED.present) check(m + ' is present', afterText.includes(m));
    check('the trigger is unchanged', JSON.stringify(after.triggers) === JSON.stringify(DEFINITION.triggers));
    check('every replaced scope matches what was sent',
          EXPECTED.changed.every((k) => JSON.stringify(after.actions[k]) === JSON.stringify(DEFINITION.actions[k])));

    say('────────────────────────────────────', T.dim);
    if (failures === 0) {
      say('Applied. ' + topBefore.length + ' -> ' + topAfter.length + ' top-level actions, trigger unchanged.', T.ok);
      say('Now test it: generate a code for A; verify it claiming to be B (must FAIL); verify as A ' +
          '(must SUCCEED); six wrong guesses (the sixth must return 429).', T.info);
    } else {
      say(failures + ' check(s) failed. Put the previous definition back with: otpPatch.rollback()', T.bad);
    }
    say('send these three numbers — not the URL: before=' + topBefore.length +
        ' after=' + topAfter.length + ' failures=' + failures, T.dim);
  };

  const rollback = async () => {
    if (!S.before || !S.found) { say('Nothing to roll back to — run otpPatch.dry() first.', T.bad); return; }
    const { res, json } = await writeDefinition(S.before);
    if (!res.ok) { say('Rollback REFUSED — ' + res.status + ' ' + safe((json && json.error && json.error.message) || ''), T.bad); return; }
    say('Rolled back to the definition read at the start of this session.', T.ok);
  };

  const status = () => {
    const hosts = [...S.tokenByOrigin.keys()].map((o) => new URL(o).hostname);
    say('origins with a token   ' + (hosts.length ? hosts.join(', ') : '(none yet)'));
    say('definition found       ' + (S.found ? new URL(S.found.url).hostname + ' — ' + S.found.shape : 'not yet — reload the flow page'));
    say('endpoints watched      ' + S.seen.length);
    say('rollback available     ' + (S.before ? 'yes' : 'no'));
  };

  const seen = () => { for (const w of S.seen) say('  ' + w, T.dim); return S.seen.length + ' endpoint(s)'; };

  window.otpPatch = { dry, apply, rollback, status, seen };
  say('otpPatch ready — dry() apply() rollback() status() seen()', T.dim);
  dry();
})();
`;

const target = path.join(ROOT, OUT);
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== js) {
    console.error(`❌ ${OUT} is stale — run: node scripts/build-otp-verify-browser-patch.mjs`);
    process.exit(1);
  }
  console.log(`✅ ${OUT} is current — ${topNew.length} top-level actions, ` +
              `${removed.length} removed, ${changed.length} replaced, trigger byte-identical`);
} else {
  writeFileSync(target, js);
  console.log(`Wrote ${OUT}`);
  console.log(`  top level   ${topLive.length} -> ${topNew.length}`);
  console.log(`  removed     ${removed.join(', ') || '(none)'}`);
  console.log(`  replaced    ${changed.join(', ') || '(none)'}`);
  console.log(`  added       ${added.join(', ') || '(none)'}`);
  console.log(`  trigger     byte-identical`);
  console.log(`  payload     ${raw.length} bytes`);
}
