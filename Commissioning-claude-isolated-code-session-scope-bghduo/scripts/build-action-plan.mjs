#!/usr/bin/env node
/**
 * The open items as an ordered action list: who acts, what they do, what closes it.
 *
 * Generated from the readiness register so it cannot drift from the statuses. Ordered by
 * dependency — items that unblock others first — then by the authority that must act.
 *
 *   node scripts/build-action-plan.mjs           # write
 *   node scripts/build-action-plan.mjs --check    # fail if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ownershipBanner } from './lib/document-ownership.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const OUT = 'docs/deployment/ACTION_PLAN.md';
const register = JSON.parse(readFileSync(join(ROOT, 'docs/deployment/PRODUCTION_READINESS_REGISTER.json'), 'utf8'));

/* DISCHARGED_UNTRACKABLE counts as closed: done, evidenced once, and unverifiable from
   this repository because the proof is a credential or a git-ignored file. See
   statusVocabulary in the register. */
const CLOSED = new Set(['RESOLVED', 'ACCEPTED', 'DISCHARGED_UNTRACKABLE']);
const open = register.items.filter(i => !CLOSED.has(i.status));

/* Order: what unblocks the most goes first. CFG-1 and CFG-2 gate every endpoint test, so they
   lead; the agency decisions can run in parallel with everything and are listed after the work
   that depends on nothing. */
const FIRST = ['CFG-1', 'CFG-2', 'ITEM-2', 'MANUAL-2', 'ITEM-43', 'ITEM-56', 'ITEM-44'];
const rank = i => {
  const f = FIRST.indexOf(i.id);
  if (f >= 0) return f;
  if (i.status === 'DECISION_REQUIRED') return 500;
  return 100 + FIRST.length;
};
/* Byte order, not locale: a tracked file must regenerate identically on every machine. */
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
const ordered = [...open].sort((a, b) => rank(a) - rank(b) || byId(a, b));

const esc = s => String(s ?? '').replace(/\s+/g, ' ').trim();

const body = ordered.map((i, n) => {
  const steps = (Array.isArray(i.steps) ? i.steps : [])
    .map(s => `   ${esc(s)}`).join('\n');
  const deps = Array.isArray(i.dependencies) && i.dependencies.length
    ? `\n**Blocked by** ${i.dependencies.join(', ')}` : '';
  return `### ${n + 1}. ${i.id} — ${esc(i.title)}

**Status** ${i.status}  ·  **Acts** ${esc(i.owner)}${deps}

**Do**
${steps || '   (no steps recorded in the register)'}

**Closes when** ${esc(i.resolutionCriteria)}
`;
}).join('\n---\n\n');

const counts = {};
for (const i of open) counts[i.status] = (counts[i.status] || 0) + 1;

const md = `# Action plan — the ${open.length} open items

${ownershipBanner('docs/deployment/ACTION_PLAN.md')}

Generated by \`npm run actions\` from [\`PRODUCTION_READINESS_REGISTER.json\`](./PRODUCTION_READINESS_REGISTER.json).
Do not edit by hand — \`npm run test:actions\` fails on drift.

${register.items.length} items in the register. ${register.items.length - open.length} closed.
**${open.length} open**: ${Object.entries(counts).sort((x, y) => (x[0] < y[0] ? -1 : x[0] > y[0] ? 1 : 0)).map(([k, v]) => `${v} ${k}`).join(', ')}.

Ordered by what unblocks the most. Items 1–${FIRST.length} come first because the rest depend on
them; the agency decisions are last only because nothing else waits on them being done in order.

Nothing here is closable from this repository. Each item names the party that acts.

---

${body}`;

if (CHECK) {
  let cur = null;
  try { cur = readFileSync(join(ROOT, OUT), 'utf8'); } catch { /* absent */ }
  if (cur !== md) {
    console.error(`❌ ${OUT} is stale — run: npm run actions`);
    process.exit(1);
  }
  console.log(`✅ ${OUT} is current — ${open.length} open items, each with an actor and steps`);
} else {
  writeFileSync(join(ROOT, OUT), md);
  console.log(`Wrote ${OUT} — ${open.length} open items`);
}
