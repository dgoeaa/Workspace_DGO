#!/usr/bin/env node
/**
 * Generate one devtools-console snippet per designer-paste package.
 *
 * WHY NOT POWERSHELL
 *   Applying these by PowerShell needs Microsoft.PowerApps.PowerShell and a signed-in module
 *   session. A console snippet needs none of that, no Entra app registration and no tenant
 *   admin — it uses the token the Power Automate portal already holds, exactly as
 *   scripts/provision-sharepoint-fields.browser.js uses the SharePoint session.
 *
 * WHY ONE SNIPPET PER PACKAGE
 *   A console cannot read the repository, so each package has to travel inside its own snippet.
 *   One snippet per flow is also the safer unit: you apply one, exercise that endpoint, and only
 *   then move on.
 *
 * WHAT A SNIPPET DOES
 *   Reads the flow, replaces the ONE top-level action whose name matches the package's nodeId,
 *   and writes the whole definition back. A designer-paste package is a clipboard SCOPE, not a
 *   definition — writing one over properties.definition would replace the flow with a single
 *   scope and destroy it. If the flow has no top-level action of that name the snippet stops and
 *   says so, because a scope with no existing home has no unambiguous placement.
 *
 *   node scripts/build-console-apply.mjs           # write
 *   node scripts/build-console-apply.mjs --check    # fail if stale
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const OUT_DIR = 'docs/deployment/internal/flows/console-apply';
const ENVIRONMENT = 'defaultca6a4b3f912349bcbcb927085ebbf1';

const SOURCES = [
  'docs/deployment/internal/flows/designer-paste',
  'docs/deployment/sharepoint/flows/designer-paste',
].filter(d => existsSync(join(ROOT, d)));

const register = JSON.parse(readFileSync(join(ROOT, 'docs/reference/endpoint-register.json'), 'utf8'));
/* Package names key on the CONTRACT, not the flow: DGO_SEND_EMAIL is the package for the
   endpoint key DGO_ENDPOINT_EMAIL, whose flow is IP_SEND_EMAIL. Matching on flow_name found one
   package in seventeen. Normalising both sides to the contract suffix is what actually joins
   them: strip the surface prefix and the _ECM_DOCS suffix the portal packages carry. */
const contractOf = s => String(s)
  .replace(/^DGO_ENDPOINT_/, '').replace(/^PF_ENDPOINT_/, '')
  .replace(/^DGO_/, '').replace(/^Portal_/i, '')
  .replace(/_ECM_DOCS$/i, '')
  .toUpperCase();

/* Three packages name their contract differently from the endpoint key. Each alias is stated
   with the flow it resolves to, because the flow name is the evidence that the two are one
   thing — not a resemblance:
     SEND_EMAIL             -> EMAIL           both are IP_SEND_EMAIL
     DYNAMIC_GLOBAL_ACTIONS -> DYNAMIC_ACTIONS both are IP_Dynamic_Global_Actions_Endpoint
     OTP                    -> OTP_VERIFY      both are IP_OTP_VERIFY
   DGO_SCHEDULED_SWEEP has no alias because it has no HTTP endpoint: it is a recurrence flow,
   so no contract key names it and no snippet can be generated. Apply that one in the designer. */
const CONTRACT_ALIASES = new Map([
  ['SEND_EMAIL', 'EMAIL'],
  ['DYNAMIC_GLOBAL_ACTIONS', 'DYNAMIC_ACTIONS'],
  ['OTP', 'OTP_VERIFY'],
]);

const flowIdByContract = new Map();
const flowNameByContract = new Map();
for (const e of Object.values(register.current_configuration)) {
  const c = contractOf(e.key);
  if (!flowIdByContract.has(c)) { flowIdByContract.set(c, e.workflow_id); flowNameByContract.set(c, e.flow_name); }
}

const packages = [];
for (const dir of SOURCES) {
  for (const f of readdirSync(join(ROOT, dir)).sort()) {
    if (!f.endsWith('.designer-paste.json')) continue;
    // *.variables.designer-paste.json are companion variable declarations, not scopes.
    if (f.endsWith('.variables.designer-paste.json')) continue;
    packages.push({ dir, file: f, base: f.replace(/\.designer-paste\.json$/, '') });
  }
}

const snippet = (p, pkg, flowId) => `/*
 * Apply ${p.base} to flow ${flowId}, from a browser devtools console.
 * GENERATED by npm run console:apply — do not edit. Source: ${p.dir}/${p.file}
 *
 * NEEDS: no PowerShell, no Entra app registration, no tenant admin. You must OWN or CO-OWN
 * this flow — the portal's own user-scoped API is used, never the admin API.
 *
 * HOW TO RUN
 *   1. Sign in to https://make.powerautomate.com and open ANY flow you own, so the page holds
 *      a token for the Flow service.
 *   2. Devtools (F12) → Console. Paste this whole file. It reports first and changes nothing.
 *   3. Read the report. Set DRY_RUN to false below and paste again to apply.
 *   4. Exercise this endpoint before applying any other package.
 *
 * CONNECTION REFERENCES ARE NOT PATCHED. A scope using a connector this flow does not already
 * hold will save and then fail at run time with an unbound connection. Apply that one in the
 * designer instead, where the connection picker runs.
 */
(async () => {
  'use strict';
  const DRY_RUN = true;

  const ENVIRONMENT = ${JSON.stringify(ENVIRONMENT)};
  const FLOW_ID = ${JSON.stringify(flowId)};
  const NODE_ID = ${JSON.stringify(pkg.nodeId)};
  const SCOPE = ${JSON.stringify(pkg.serializedValue)};

  function findFlowToken() {
    const wanted = /service\\.flow\\.microsoft\\.com|management\\.azure\\.com/i;
    const out = [];
    for (const store of [window.sessionStorage, window.localStorage]) {
      for (let i = 0; i < store.length; i++) {
        const key = store.key(i);
        if (!/accesstoken/i.test(key)) continue;
        let v; try { v = JSON.parse(store.getItem(key)); } catch { continue; }
        const secret = v && (v.secret || v.accessToken);
        if (!secret) continue;
        const target = key + ' ' + (v.target || v.scopes || '');
        if (!wanted.test(target)) continue;
        out.push({ secret, expires: Number(v.expiresOn || 0), flow: /service\\.flow\\.microsoft\\.com/i.test(target) });
      }
    }
    if (!out.length) return null;
    out.sort((a, b) => (b.flow - a.flow) || (b.expires - a.expires));
    return out[0].secret;
  }

  const token = findFlowToken();
  if (!token) {
    console.log('%cNo Flow access token in this page.', 'color:#c00;font-weight:bold');
    console.log('Open https://make.powerautomate.com, open any flow you own, and paste this on that tab.');
    return;
  }

  /* WHICH HOST SERVES THIS TENANT IS NOT KNOWN, so this does not bet everything on one.
     api.flow.microsoft.com is the global endpoint and is tried first because it is what every
     snippet in this estate has always used. But tests/otp-verify-browser-patch.test.mjs records
     a management call that did not resolve there, and no run in this repository has ever
     confirmed that it does. So any ProcessSimple origin the page has ACTUALLY called is tried
     as well — observed beats assumed — and if none answers, the failure says what to do rather
     than printing a bare status. */
  const observed = [];
  try {
    for (const e of performance.getEntriesByType('resource')) {
      const m = /^(https:\\/\\/[^/]+)\\/providers\\/Microsoft\\.ProcessSimple\\//i.exec(e.name);
      if (m && !observed.includes(m[1])) observed.push(m[1]);
    }
  } catch { /* a browser without Resource Timing simply contributes no candidates */ }

  const origins = [...observed, 'https://api.flow.microsoft.com']
    .filter((o, i, a) => a.indexOf(o) === i);
  const uriFor = (origin) => origin + '/providers/Microsoft.ProcessSimple/environments/'
    + ENVIRONMENT + '/flows/' + FLOW_ID + '?api-version=2016-11-01';
  const headers = { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' };

  let uri = null, res = null;
  for (const origin of origins) {
    const attempt = await fetch(uriFor(origin), { headers });
    if (attempt.ok) { uri = uriFor(origin); res = attempt; break; }
    console.log('%c  ' + new URL(origin).hostname + ' -> ' + attempt.status, 'color:#888');
  }
  if (!res) {
    console.log('%cCould not read the flow on any host tried.', 'color:#c00;font-weight:bold');
    console.log('Tried: ' + origins.map((o) => new URL(o).hostname).join(', '));
    console.log('If every one returned 404, this flow may be solution-aware and stored in');
    console.log('Dataverse rather than at a ProcessSimple path — apply it in the designer.');
    console.log('If you have not moved around the portal since signing in, open My flows and');
    console.log('a flow or two (do NOT reload), then paste this again: that lets the snippet');
    console.log('see which host this tenant actually uses instead of guessing.');
    return;
  }
  if (uri !== uriFor('https://api.flow.microsoft.com')) {
    console.log('%cUsing ' + new URL(uri).hostname + ', observed in this page.', 'color:#268bd2');
  }
  const flow = await res.json();
  const definition = flow.properties.definition;
  const actions = definition.actions || {};

  if (!Object.prototype.hasOwnProperty.call(actions, NODE_ID)) {
    console.log('%cThis flow has no top-level scope named "' + NODE_ID + '".', 'color:#c00;font-weight:bold');
    console.log('Top-level actions present:', Object.keys(actions).join(', '));
    console.log('Nothing was changed. Paste this package in the designer, where you choose the');
    console.log('placement and bind the connections — placement is not guessed here.');
    return;
  }

  const before = JSON.stringify(actions[NODE_ID]);
  const after = JSON.stringify(SCOPE);
  if (before === after) { console.log('%cScope "' + NODE_ID + '" already matches. Nothing to do.', 'color:#080'); return; }

  console.log('%c${p.base}', 'font-weight:bold;font-size:14px');
  console.log('  flow    : ' + FLOW_ID);
  console.log('  scope   : ' + NODE_ID);
  console.log('  current : ' + before.length + ' chars');
  console.log('  incoming: ' + after.length + ' chars');

  if (DRY_RUN) {
    console.log('%cDRY RUN — WOULD REPLACE this scope. Nothing was written.', 'color:#b8860b;font-weight:bold');
    console.log('Set DRY_RUN to false at the top of this file and paste again.');
    return;
  }

  actions[NODE_ID] = SCOPE;
  const patch = await fetch(uri, { method: 'PATCH', headers, body: JSON.stringify({ properties: { definition } }) });
  if (!patch.ok) { console.log('%cPATCH failed: ' + patch.status, 'color:#c00'); return; }
  console.log('%cApplied. Now verify against the tenant rather than assuming:', 'color:#080;font-weight:bold');
  console.log('  npm run verify:endpoints');
  console.log('  npm run notifications -- --check');
})();
`;

const written = {};
const unmatched = [];
for (const p of packages) {
  const pkg = JSON.parse(readFileSync(join(ROOT, p.dir, p.file), 'utf8'));
  if (!pkg.nodeId || !pkg.serializedValue) { unmatched.push(`${p.base} (not a scope package)`); continue; }
  const raw = contractOf(p.base);
  const contract = CONTRACT_ALIASES.get(raw) || raw;
  const flowId = flowIdByContract.get(contract);
  if (!flowId) { unmatched.push(`${p.base} -> contract ${contract}, which no endpoint key names`); continue; }
  written[`${OUT_DIR}/${p.base}.console-apply.js`] = snippet(p, pkg, flowId);
}

if (CHECK) {
  const stale = Object.entries(written).filter(([f, c]) => {
    try { return readFileSync(join(ROOT, f), 'utf8') !== c; } catch { return true; }
  }).map(([f]) => relative(ROOT, join(ROOT, f)).split(sep).join('/'));
  if (stale.length) {
    console.error(`❌ console-apply snippets are stale — run: npm run console:apply\n   ${stale.slice(0, 5).join(', ')}`);
    process.exit(1);
  }
  console.log(`✅ console-apply snippets are current — ${Object.keys(written).length} of ${packages.length} packages, ${unmatched.length} without a flow`);
} else {
  rmSync(join(ROOT, OUT_DIR), { recursive: true, force: true });
  mkdirSync(join(ROOT, OUT_DIR), { recursive: true });
  for (const [f, c] of Object.entries(written)) writeFileSync(join(ROOT, f), c);
  console.log(`Wrote ${OUT_DIR}`);
  console.log(`  snippets  : ${Object.keys(written).length}`);
  console.log(`  packages  : ${packages.length}`);
  if (unmatched.length) { console.log(`  no flow   : ${unmatched.length}`); unmatched.forEach(u => console.log(`     ${u}`)); }
}
