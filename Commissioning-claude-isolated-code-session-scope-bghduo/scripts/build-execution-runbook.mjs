#!/usr/bin/env node
/**
 * In what order can the readiness register's items actually be executed?
 *
 * WHY THIS IS COMPUTED, NOT WRITTEN
 * The register records each item's dependencies. The execution ORDER is implied by them, and an
 * order written by hand beside a dependency list is a second source of truth that drifts from the
 * first — silently, because nothing compares them. So this derives the order: a topological sort
 * over the register's own `dependencies`, grouped into waves, where a wave is the set of items
 * whose blockers have all cleared in earlier waves.
 *
 * A wave is not a promise that its items are done together. It says only that nothing in it waits
 * on anything else in it, so they may be worked in any order, or at once, by whoever owns them.
 *
 * WHAT IT CANNOT TELL YOU
 * Nothing here schedules. The register records no target date for any item — none is established
 * anywhere in the estate — so this produces a sequence, never a plan with dates. It also cannot
 * know how long a wave takes, because no item has ever been executed against the tenant.
 *
 * Items whose dependency text is free-form rather than an item id are treated as having no
 * in-register blocker, and the free text is carried into the runbook so the reader sees the
 * condition the sort could not model.
 *
 * Usage:
 *   node scripts/build-execution-runbook.mjs            # write the runbook
 *   node scripts/build-execution-runbook.mjs --check    # fail if the written file is stale
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { byteCompare } from './lib/stable-sort.mjs';
import { ownershipBanner } from './lib/document-ownership.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const reg = JSON.parse(readFileSync(join(ROOT, 'docs/deployment/PRODUCTION_READINESS_REGISTER.json'), 'utf8'));
const TARGET = 'docs/deployment/EXECUTION_RUNBOOK.md';
const check = process.argv.includes('--check');

const byId = new Map(reg.items.map((i) => [i.id, i]));

/* The two statuses that mean an item is done. RESOLVED is closed on evidence; ACCEPTED is
   closed by a recorded risk acceptance. Everything else is outstanding. */
/* DISCHARGED_UNTRACKABLE counts as closed: done, evidenced once, and unverifiable from
   this repository because the proof is a credential or a git-ignored file. See
   statusVocabulary in the register. */
const CLOSED = new Set(['RESOLVED', 'ACCEPTED', 'DISCHARGED_UNTRACKABLE']);
const ID_RE = /^((?:ITEM|CFG|MANUAL|G)-[A-Z0-9]+)/;

/** Split each item's dependencies into ones this register can resolve and ones it cannot. */
const deps = new Map();
const freeText = new Map();
for (const it of reg.items) {
  const hard = [], soft = [];
  for (const d of it.dependencies || []) {
    const m = String(d).match(ID_RE);
    if (m && byId.has(m[1])) hard.push(m[1]); else soft.push(String(d));
  }
  deps.set(it.id, hard);
  freeText.set(it.id, soft);
}

/* Topological sort into waves. An item enters the first wave in which every id it waits on has
   already been placed. A cycle would leave items unplaced; that is reported rather than hidden. */
const waves = [];
const placed = new Set();
let remaining = reg.items.map((i) => i.id);
while (remaining.length) {
  const wave = remaining.filter((id) => deps.get(id).every((d) => placed.has(d)));
  if (!wave.length) {
    console.error(`❌ dependency cycle among: ${remaining.join(', ')}`);
    process.exit(1);
  }
  wave.sort((a, b) => {
    const pa = byId.get(a), pb = byId.get(b);
    const rank = (x) => (x.category === 'BLOCKING' ? 0 : x.category === 'PROVISIONING' ? 1
      : x.category === 'APPLY' ? 2 : x.category === 'UNSPECIFIED' ? 3 : 4);
    return rank(pa) -byteCompare( rank(pb) || a, b);
  });
  waves.push(wave);
  wave.forEach((id) => placed.add(id));
  remaining = remaining.filter((id) => !wave.includes(id));
}

/* Owners per wave, so a reader can see who is needed when. */
const ownersOf = (wave) => [...new Set(wave.map((id) => byId.get(id).owner))].sort();

let md = `# Execution runbook

${ownershipBanner('docs/deployment/EXECUTION_RUNBOOK.md')}
>
> The command-line commissioning path is
> [\`CLEAR-THE-LAST-BLOCKER.md\`](./CLEAR-THE-LAST-BLOCKER.md) — on a phone,
> [\`CLEAR-THE-LAST-BLOCKER-TERMUX.md\`](./CLEAR-THE-LAST-BLOCKER-TERMUX.md).

**Generated by \`node scripts/build-execution-runbook.mjs\` from
[\`PRODUCTION_READINESS_REGISTER.json\`](./PRODUCTION_READINESS_REGISTER.json).** Do not edit by
hand — the order below is a topological sort over the register's own \`dependencies\`, so editing
this file makes it disagree with the data it came from. Change the register and regenerate.

Register version ${reg.registerVersion}, compiled against commit \`${reg.compiledAgainstCommit}\`
on ${reg.compiledUtc}. ${reg.items.length} items in ${waves.length} waves.

## What a wave means

A wave is the set of items whose blockers have all cleared in earlier waves. Nothing in a wave
waits on anything else in the same wave, so its items may be worked in any order, or at once, by
whoever owns them. **A wave is not a schedule.** No item in this register carries a target date —
none is established anywhere in the estate — and no item has ever been executed against the
tenant, so nothing here can say how long a wave takes.

## What is not modelled

Some dependencies are conditions rather than items — a licensing confirmation, a decision, a
deployed build to test against. The sort cannot order those, so they are carried into each item
as **Also waits on** and must be read before starting it.

`;

waves.forEach((wave, n) => {
  md += `\n---\n\n## Wave ${n + 1} — ${wave.length} item(s)\n\n`;
  md += `**Owners needed:** ${ownersOf(wave).join(' · ')}\n\n`;
  for (const id of wave) {
    const it = byId.get(id);
    md += `### ${id} — ${it.title}\n\n`;
    md += `| | |\n|---|---|\n`;
    md += `| **Status** | ${it.status} |\n`;
    md += `| **Category** | ${it.category} |\n`;
    md += `| **Owner** | ${it.owner} |\n`;
    md += `| **Target date** | ${it.targetDate ?? '_none established_'} |\n`;
    const hard = deps.get(id);
    md += `| **Waits on (in register)** | ${hard.length ? hard.join(', ') : '_nothing_'} |\n`;
    const soft = freeText.get(id);
    if (soft.length) md += `| **Also waits on** | ${soft.join(' · ')} |\n`;
    md += `\n${it.description}\n\n`;
    /* THE LABEL HAS TO FOLLOW THE STATUS.
       This read `**Why it is still open.**` for every item, closed ones included, so all 24
       closed items in this runbook were printed under that heading followed by their own
       closure sentence — `Why it is still open. Resolved 2026-09-03.` A reader scanning the
       runbook for what is outstanding found 48 items presented as open. The register field is
       still named whyOpen because it answers that question for the items that are open; for a
       closed one it answers the opposite question, and the heading now says which. */
    md += `**${CLOSED.has(it.status) ? 'Why it closed' : 'Why it is still open'}.** ${it.whyOpen}\n\n`;
    if (it.constraints?.length) {
      md += `**Constraints**\n\n${it.constraints.map((c) => `- ${c}`).join('\n')}\n\n`;
    }
    if (it.decisions?.length) {
      md += `**Decisions required first**\n\n${it.decisions.map((c) => `- ${c}`).join('\n')}\n\n`;
    }
    md += `**Steps**\n\n${it.steps.map((s) => `- ${s.replace(/^\d+\.\s*/, '')}`).join('\n')}\n\n`;
    md += `**Done when.** ${it.resolutionCriteria}\n\n`;
    md += `**Validated by.** ${it.validation}\n\n`;
  }
});

md += `\n---\n\n## Coverage\n\n`;
md += `| Wave | Items |\n|---|---|\n`;
waves.forEach((w, n) => { md += `| ${n + 1} | ${w.join(', ')} |\n`; });
md += `\nEvery one of the ${reg.items.length} register items appears exactly once above.\n`;

if (check) {
  const cur = existsSync(join(ROOT, TARGET)) ? readFileSync(join(ROOT, TARGET), 'utf8') : '';
  if (cur !== md) {
    console.error(`❌ ${TARGET} is stale — run: node scripts/build-execution-runbook.mjs`);
    process.exit(1);
  }
  console.log(`✅ ${TARGET} matches the register`);
  process.exit(0);
}

writeFileSync(join(ROOT, TARGET), md);
console.log(`wrote ${TARGET}`);
waves.forEach((w, n) => console.log(`  wave ${n + 1}: ${w.length} item(s) — ${w.join(', ')}`));
console.log(`  owners across all waves: ${[...new Set(reg.items.map((i) => i.owner))].sort().join(' · ')}`);
