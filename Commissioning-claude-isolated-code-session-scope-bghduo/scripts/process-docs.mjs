#!/usr/bin/env node
/**
 * Render the process documentation package from the master inventory.
 *
 *   node scripts/process-docs.mjs
 *
 * Nothing is written here that is not in docs/reference/process-inventory.json, and nothing
 * in that file is invented: it is produced by scripts/process-discovery.mjs, which reads only
 * artifacts held in this repository. If a statement in these documents is wrong, the artifact
 * it cites is wrong, or the discovery script read it wrongly — there is no third possibility
 * and no prose written by hand in between.
 *
 * The package is laid out as the twenty-eight items the documentation standard requires, in
 * its order, one file each, plus one detail file per process.
 */
import { writeFileSync, mkdirSync, rmSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { expand, cell, mm, table, COV, EV } from './process/lib.mjs';

const ROOT = process.cwd();
const OUT = join(ROOT, 'docs/process');
const raw = JSON.parse(readFileSync(join(ROOT, 'docs/reference/process-inventory.json'), 'utf8'));
const D = expand(raw, raw.phrases || []);

/* A repository holds part of the estate. Where the same generator runs over a sibling
   repository holding the rest, a reader of THIS package needs to know that, or the coverage
   register's "insufficient evidence" rows read as "documented nowhere" rather than
   "documented in the repository named here". The note is a file in the repository rather than
   a string in this script, so each repository states its own position and neither script has
   to make a claim about a tree it cannot read. */
const SCOPE_NOTE = existsSync(join(ROOT, 'docs/process-scope-note.md'))
  ? readFileSync(join(ROOT, 'docs/process-scope-note.md'), 'utf8').trim()
  : '';

const files = [];
const write = (rel, body) => {
  const p = join(OUT, rel);
  mkdirSync(join(p, '..'), { recursive: true });
  writeFileSync(p, body.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
  files.push(rel);
};

/* Standing header. Every document says where it came from and what it may not be used for. */
const HEAD = (n, title, purpose) => `# ${n}. ${title}

> **Generated.** Produced by \`scripts/process-docs.mjs\` from \`docs/reference/process-inventory.json\`,
> which \`scripts/process-discovery.mjs\` builds by reading the artifacts in this repository.
> Do not edit this file: edit the artifact, or the script that reads it, and regenerate.
> Inventory generated ${D.generated}. Standard \`${D.standard}\`.

**Purpose.** ${purpose}

`;

const byId = Object.fromEntries([...D.processes, ...D.subprocesses].map(p => [p.id, p]));
const srcById = Object.fromEntries(D.sources.map(s => [s.id, s]));
const stepsOf = {};
for (const s of D.steps) (stepsOf[s.process] ||= []).push(s);
const decsOf = {}; for (const d of D.decisions) (decsOf[d.process] ||= []).push(d);
const excOf = {}; for (const e of D.exceptions) (excOf[e.process] ||= []).push(e);
const notOf = {}; for (const n of D.notifications) (notOf[n.process] ||= []).push(n);
const monOf = {}; for (const m of D.monitoring) (monOf[m.process] ||= []).push(m);
const ctrlOf = {}; for (const c of D.controls) (ctrlOf[c.process || c.affectedProcess] ||= []).push(c);
const ruleOf = {}; for (const r of D.rules) (ruleOf[r.affectedProcess] ||= []).push(r);
const depOf = {}; for (const d of D.dependencies) for (const k of String(d.dependentProcess || '').split(', ')) (depOf[k] ||= []).push(d);
const varOf = {}; for (const v of D.variants) (varOf[v.parentProcess] ||= []).push(v);
const subOf = {}; for (const s of D.subprocesses) (subOf[s.parentProcess] ||= []).push(s);

const srcLinks = ids => (ids || []).map(i => srcById[i] ? `\`${i}\` ${srcById[i].path}` : i);
const detailPath = p => `detail/${p.id}.md`;

/* A detail file is written for every process, and for every subprocess that carries steps of
   its own — the hidden technical routes have their own module and their own governed writes,
   so summarising them into a catalogue row would lose the ten sections the standard requires.
   A governed-action subprocess has no steps beyond the one that raises it and is documented in
   full in the subprocess catalogue, so a link to it points there rather than at a file that
   would only repeat the row. */
const DETAILED = new Set([...D.processes.map(p => p.id),
  ...D.subprocesses.filter(s => (stepsOf[s.id] || []).length).map(s => s.id)]);
const link = (id, from = '') => {
  if (!byId[id]) return id || '—';
  const up = from === 'detail' ? '../' : '';
  return DETAILED.has(id)
    ? `[${id}](${up}${detailPath(byId[id])})`
    : `[${id}](${up}10-SUBPROCESS-AND-VARIANT-CATALOGUE.md)`;
};

/* Counts used in several documents; computed once so they cannot disagree. */
const n = {
  proc: D.processes.length, sub: D.subprocesses.length, step: D.steps.length,
  dec: D.decisions.length, variant: D.variants.length, rule: D.rules.length,
  ctrl: D.controls.length, exc: D.exceptions.length, notif: D.notifications.length,
  mon: D.monitoring.length, dep: D.dependencies.length, gap: D.gaps.length,
  stat: D.statuses.length, tran: D.transitions.length, int: D.integrations.length,
  role: D.roles.length, sys: D.systems.length, mod: D.modules.length, src: D.sources.length,
};
const evCount = (arr) => {
  const c = {};
  for (const x of arr) if (x.evidence) c[x.evidence] = (c[x.evidence] || 0) + 1;
  return c;
};
const ALL_RECORDS = [...D.processes, ...D.subprocesses, ...D.steps, ...D.decisions, ...D.variants,
  ...D.rules, ...D.controls, ...D.exceptions, ...D.notifications, ...D.monitoring,
  ...D.dependencies, ...D.statuses, ...D.transitions, ...D.integrations, ...D.roles,
  ...D.systems, ...D.modules, ...D.gaps];
const EV_TOTALS = evCount(ALL_RECORDS);

/* ═════════════ 01 Executive summary ═════════════ */
