#!/usr/bin/env node
/**
 * THE ESTATE, IN ONE DOCUMENT.
 *
 * WHY THIS EXISTS
 *
 * This is the documentation that ordinarily exists before development starts: what the platform
 * is, what it is made of, how a request travels through it, what it stores, and the rules it is
 * built to. It did not exist here, because the estate grew — a second surface, then a third,
 * then flows that were not in any plan — and each addition was documented where it landed rather
 * than into one description. By 2026-09-24 there were thirty-six documents under one directory,
 * several describing the same thing in different words and a few describing a thing that had
 * since changed.
 *
 * The answer to that is not a thirty-seventh hand-written document. Every fact below is read
 * from the register or the reference data that the gates already hold to be true, so this page
 * cannot say something the estate contradicts: if it drifts, `npm run test:platform` fails, and
 * the fix is to correct the source rather than the prose.
 *
 * WHAT IS HAND-WRITTEN HERE
 *
 * The connective tissue — why the parts fit together the way they do. That judgement is not in
 * any register and should not be invented from one. It is kept short, and it is kept separate
 * from the generated tables so a reader can tell which is which.
 *
 *     node scripts/build-platform-doc.mjs            # write it
 *     node scripts/build-platform-doc.mjs --check    # exit 1 if it drifted
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { byteCompare } from './lib/stable-sort.mjs';
import { Brand } from '../config/brand.config.js';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'docs/PLATFORM.md');
const J = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

const REG = J('docs/deployment/PRODUCTION_READINESS_REGISTER.json');
const ENDPOINTS = J('docs/folio-Master-Flows-and-Endpoints/registers/endpoint-register.json');
const MAP = J('docs/folio-Master-Flows-and-Endpoints/reference/contract-key-flow-map.json');
const RECON = J('docs/folio-Master-Flows-and-Endpoints/reference/contract-key-flow-reconciliation.json');
const POSTURE = J('docs/folio-Master-Flows-and-Endpoints/registers/flow-trigger-auth.json');
const SP = J('docs/reference/sharepoint-provisioning-spec.json');
const LEDGER = J('docs/reference/internal-proof-ledger.json');
const PKG = J('package.json');

const CLOSED = new Set(['RESOLVED', 'ACCEPTED', 'DISCHARGED_UNTRACKABLE']);
const open = REG.items.filter((i) => !CLOSED.has(i.status));
const gates = Object.keys(PKG.scripts).filter((k) => k.startsWith('test:') && k !== 'test:node' && k !== 'test:smoke');

const L = [];
const p = (...s) => L.push(...s);

p(`# ${Brand.estate}`);
p('');
p('<!-- Generated by scripts/build-platform-doc.mjs. Do not edit by hand: run `npm run platform`.');
p('     `npm run test:platform` fails if it drifts from the registers it is built from. -->');
p('');
p('> **This document carries no commands.** It describes the estate. What to do about it is in');
p('> [`deployment/PLAN.md`](deployment/PLAN.md); how to do it is in');
p('> [`deployment/RUNBOOK.md`](deployment/RUNBOOK.md). Those three are the whole documentation set.');
p('');
p('## 1 · What this is');
p('');
p('A document and correspondence estate for a government agency, built as **static browser');
p('applications calling Power Automate flows directly**. There is no server tier and no API');
p('gateway. A page in a browser holds a signed trigger URL for each operation it needs and posts');
p('to it; the flow reads and writes SharePoint lists and answers. That one decision explains most');
p('of what follows — in particular why authorisation has to live inside each flow, and why a');
p('trigger URL is a credential rather than an address.');
p('');
p('### The surfaces');
p('');
p('| Surface | Port | What it is |');
p('| --- | --- | --- |');
p(`| ${Brand.platforms.runtime} | 8080 | The operations platform — routing, RBAC, state, the Admin Suite |`);
p(`| ${Brand.platforms.portal} | 8081 | Public submission and tracking; a PWA with its own origin |`);
p(`| ${Brand.platforms.mailer} | 8083 | Personalised letters through seven flows, published beside the Workspace |`);
p(`| ${Brand.platforms.capsule} | 8787 | Holds signed flow URLs behind aliases; optional for the Workspace, required for the Portal before public launch |`);
p(`| ${Brand.platforms.centre} | 8844 | The control plane, with the ${Brand.platforms.console} as a section and Test a flow (the Flow Workbench and the Platform Hub were retired into it) |`);
p('');
p('They are zero-build static sites. `npm run platforms` lists them; each starts on its own port');
p('so an origin-scoped service worker behaves as it will in production.');
p('');
p('## 2 · How a request travels');
p('');
p('```');
p('  browser  ──POST signed trigger URL──▶  Power Automate flow');
p('                                              │');
p('                                              ├─ resolve the caller');
p('                                              ├─ resolve that caller’s role from the directory');
p('                                              ├─ decide: permitted?');
p('                                              ├─ read / write SharePoint lists');
p('                                              └─ answer a standard envelope');
p('```');
p('');
p('Every governed step in that chain happens **inside the flow**. There is nowhere else for it to');
p('happen: the browser is the client, and between the browser and SharePoint there is only the');
p('flow. A client-side route guard is user experience; it is not enforcement.');
p('');
p('## 3 · Identity');
p('');
p('There is no external identity provider. Identity is established by emailed one-time code:');
p('');
p('1. `OTP_GENERATE` mails a code to an address that must already exist, and be active, in the');
p('   user directory.');
p('2. `OTP_VERIFY` exchanges a correct code for a **proof** — an opaque token written to a ledger');
p('   with the address it was issued to and an expiry.');
p('3. Every other endpoint reads the token from the `Authorization` header, looks it up, and takes');
p('   the caller’s address **from the ledger row**, never from the request body.');
p('');
p('The proof is a row rather than a signed structure because Power Automate has no signing');
p('function. The ledger is what makes the token mean anything, and revoking one proof is a');
p(`\`Consumed\` flag rather than a key rotation. Internal proofs live ${LEDGER.listId ? 'in their own ledger' : 'in the portal’s ledger for now — a separate list is decided and not yet provisioned'}.`);
p('');
p('Because the trigger URL is itself the credential that gets you to the flow, and because the');
p('flow then decides for itself who you are, **a leaked trigger URL is not sufficient to read');
p('data — but a flow that trusts the request body makes it sufficient.** That is the single most');
p('important property of this design to preserve.');
p('');
p('## 4 · The wired estate');
p('');
p(`${ENDPOINTS.current_configuration.length} contract keys are wired. ${MAP.counts.keys} are named in the flow map.`);
p(`Of those, ${RECON.counts.confirmed} are already served by the flow the map names,`);
p(`${RECON.counts.suppliedByTheMap} were unresolved by any tenant reading until the map supplied them, and`);
p(`${RECON.counts.migrations} are served by a different flow from the one intended.`);
p('');
p('| Contract key | Flow | Surface |');
p('| --- | --- | --- |');
for (const r of [...MAP.map].sort((a, b) => byteCompare(a.contractKey, b.contractKey))) {
  p(`| \`${r.contractKey}\` | ${r.expectedFlowName} | ${r.contractKey.startsWith('CG_') ? 'portal' : 'internal'} |`);
}
p('');
p('### Trigger posture');
p('');
p(`${POSTURE.scope.reads}`);
p('');
p('An open trigger is not by itself a defect here: the platform authenticates in the flow, not at');
p('the trigger, and the one flow that historically required tenant sign-in did so because its');
p('caller arrives as a platform-supplied principal rather than in a body it could read.');
p('');
p('## 5 · What it stores');
p('');
p(`${SP.lists.length} SharePoint lists carry the estate, specified across ${SP.fields.length} fields.`);
p('');
p('| List | Fields | Purpose |');
p('| --- | --- | --- |');
for (const l of SP.lists) p(`| \`${l.ListTitle}\` | ${l.FieldCount} | ${String(l.Purpose || '').replace(/\|/g, '/')} |`);
p('');
p('`DGO_UserDirectory` and `DGO_RoleCatalogue` are the two that matter most to §3: the first says');
p('who exists and whether they are active, the second says what their role may do. Every');
p('authorisation decision in the estate resolves through that pair.');
p('');
p('## 6 · How this documentation is kept true');
p('');
p('The record of account is');
p('[`deployment/PRODUCTION_READINESS_REGISTER.json`](deployment/PRODUCTION_READINESS_REGISTER.json)');
p(`— version ${REG.registerVersion}, ${REG.items.length} items, ${open.length} of them open. Every document here is`);
p('generated from it or from the reference data beside it, and each carries a check that fails on');
p('drift. The governing rule, applied throughout:');
p('');
p('> **Where a document and a command disagree, the command governs.**');
p('');
p(`\`npm run test:node\` runs ${gates.length} such checks. They are not decoration: several of the findings in`);
p('the register were caught by a gate failing on a change its author believed was safe, and the');
p('register pins itself to a commit so that evidence citations cannot quietly rot.');
p('');
p('## 7 · Where the work stands');
p('');
p('| Status | Items | Means |');
p('| --- | --- | --- |');
const vocab = REG.statusVocabulary || {};
const counts = {};
for (const i of open) counts[i.status] = (counts[i.status] || 0) + 1;
for (const [s, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) {
  p(`| ${s} | ${n} | ${String(vocab[s] || '').split('.')[0]} |`);
}
p('');
p('The detail, with what closes each one, is in [`deployment/PLAN.md`](deployment/PLAN.md).');
p('');

/* THE REGISTER IS ONE SOURCE OF FIVE, AND SAYING SO IS THE POINT OF SAYING IT.
 *
 * The table above counts the readiness register, and for a long time that count was quoted as
 * the estate's. It is not: the governance position, the notification workstream's own pending
 * register, the notification assessment and the flow-truth review each track work the register
 * does not, and two of the flow-truth findings are security findings. `npm run outstanding`
 * totals all five and is the only thing that does. A platform document that printed one of the
 * five as the whole would be understating the work by more than half. */
{
  const roll = JSON.parse(readFileSync(join(ROOT, 'docs/deployment/outstanding-rollup.json'), 'utf8'));
  const t = roll.totals;
  p(`That table is the **readiness register alone**, which is one of ${t.sourcesCounted} places this`);
  p(`estate records outstanding work. Across all ${t.sourcesCounted}, declared in`);
  p('[`deployment/OUTSTANDING_SOURCES.json`](deployment/OUTSTANDING_SOURCES.json) and totalled by');
  p(`\`npm run outstanding\`, **${t.open} items are outstanding** and ${t.closed} are closed:`);
  p('');
  p('| Source | Open | Closed |');
  p('| --- | ---: | ---: |');
  for (const src of roll.sources) p(`| ${src.title} | ${src.open} | ${src.closed} |`);
  p(`| **Total** | **${t.open}** | **${t.closed}** |`);
  p('');
  p('The count is federated rather than merged on purpose: each source owns its own items and its');
  p('own closing conditions, and merging them would mean one register deciding when another');
  p("register's finding is closed. The rollup totals them; it does not adjudicate between them.");
  p('');
}

/* THE ARCHITECTURE, CARRIED RATHER THAN RESTATED.
 *
 * PLATFORM_DOCUMENTATION.md stood at the repository root until 2026-09-24: 350 hand-written lines
 * dated 2 August, describing the same estate as this file in different words and, in places, in a
 * state it had left behind — its authentication section still called the client half switched off
 * with activation a configuration change away, which stopped being the whole picture the day the
 * proof chain was built.
 *
 * Its architecture is not stale, though, and no register holds it: the layering, the boot
 * sequence, the routing model, the governance spine, the design system. That cannot be generated
 * and should not be re-typed, so it lives in scripts/platform-parts/ and is embedded below. The
 * three sections this file already states from the registers were dropped on the way in rather
 * than carried twice. */
const PARTS = join(ROOT, 'scripts/platform-parts');
for (const f of readdirSync(PARTS).filter((x) => x.endsWith('.md')).sort(byteCompare)) {
  const raw = readFileSync(join(PARTS, f), 'utf8').replace(/\r\n/g, '\n').trim()
    .replace(/^<!--[\s\S]*?-->\n?/, '')
    .replace(/\]\(\.\.\/\.\.\/docs\//g, '](./');
  p('---', '');
  p('# The architecture', '');
  p('Everything above is read from the registers and regenerated on every change. What follows is');
  p('hand-written: the shape of the thing, which no register holds.');
  p('');
  let fenced = false;
  for (const line of raw.split('\n')) {
    if (/^\s*```/.test(line)) fenced = !fenced;
    p(!fenced && /^#{1,5} /.test(line) ? '#' + line : line);
  }
  p('');
}

const built = L.join('\n');

if (process.argv.includes('--check')) {
  const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return null; } })();
  if (current !== built) {
    console.log(`\n❌ ${relative(ROOT, OUT)} drifted from the registers. Run: npm run platform\n`);
    process.exit(1);
  }
  console.log(`\n✅ ${relative(ROOT, OUT)} matches the estate`);
  console.log(`   ${MAP.counts.keys} contract keys · ${SP.lists.length} lists · ${gates.length} gates · ${open.length} open items\n`);
  process.exit(0);
}
writeFileSync(OUT, built);
console.log(`Wrote ${relative(ROOT, OUT)} — ${MAP.counts.keys} keys, ${SP.lists.length} lists, ${open.length} open items.`);
