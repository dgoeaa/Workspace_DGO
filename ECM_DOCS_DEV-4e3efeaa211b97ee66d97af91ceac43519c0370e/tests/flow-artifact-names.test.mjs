#!/usr/bin/env node
/**
 * Flow artefact file names (identifier catalogue namingConventions.flowArtifactFile, spec §17).
 *
 * A file about a flow says which endpoint, which flow and which tenant flow it is:
 * <CONTRACT_KEY>__<FlowName>__<flow-id8>[__<Part>].<kind>. This holds the identification packages to it, and holds the
 * identities they are named with to the tenant captures and the catalogue, so a name cannot claim a key or an id the
 * evidence does not give.
 */
import { readFileSync, readdirSync } from 'node:fs';
import { openZip } from '../scripts/lib/zip-reader.mjs';
import { FLOW_ARTIFACT_RE, FLOW_IDENTITIES, NOKEY, NOT_CAPTURED, parseFlowArtifactName, flowNameSegment, flowIdPart } from '../scripts/lib/flow-artifact-name.mjs';

let pass = 0, fail = 0;
const ok = (c, m, d = '') => { c ? (pass++, console.log(`  ✅ ${m}`)) : (fail++, console.log(`  ❌ ${m}${d ? ` — ${d}` : ''}`)); };
const ROOT = 'docs/folio-Master-Flows-and-Endpoints';
const CAT = JSON.parse(readFileSync('docs/reference/identification/identifier-catalogue.json', 'utf8'));
const conv = CAT.namingConventions.flowArtifactFile;
console.log('\nFlow artefact file names\n');

ok(conv && conv.pattern === FLOW_ARTIFACT_RE.source, 'the catalogue\'s pattern is the one scripts/lib/flow-artifact-name.mjs applies');
ok(conv.examples.every((e) => FLOW_ARTIFACT_RE.test(e.value)), 'every valid example in the catalogue meets the pattern');
ok(conv.invalidExamples.every((e) => !FLOW_ARTIFACT_RE.test(e.value)), 'no invalid example in the catalogue meets it');

/* The identities the packages are named with. */
const keys = new Set(Object.keys(CAT.contractKeyProcess));
const captures = Object.fromEntries(readdirSync(`${ROOT}/captures`).map((f) => /^(.+)__([0-9a-f-]{36})\.json$/.exec(f)).filter(Boolean).map((m) => [flowNameSegment(m[1]), m[2]]));
/* A tenant export is the other evidence of a flow's id: the flow's definition.json names it
   (/providers/Microsoft.Flow/flows/<id>). The package's resource folder id is generated by the export and is not it. */
/* Every export counts, in the convention or not (an older export keeps its name where records cite it): its definition
   gives the flow's display name and id together. A name in the convention must agree with them. */
for (const f of readdirSync(`${ROOT}/exports`).filter((x) => x.endsWith('.zip'))) {
  const n = parseFlowArtifactName(f);
  const def = openZip(`${ROOT}/exports/${f}`).members.find((m) => /Microsoft\.Flow\/flows\/[^/]+\/definition\.json$/.test(m.name));
  const d = def ? JSON.parse(def.read().toString('utf8')) : null;
  const named = d?.name ?? null;
  if (n && n.kind === 'zip') {
    ok(named && flowIdPart(named) === n.id && flowNameSegment(d.properties?.displayName ?? '') === n.flow, `exports/${f}: the export's definition names flow ${n.flow} ${n.id}…`, `definition.json ${d?.properties?.displayName} ${named}`);
  }
  if (named && d.properties?.displayName) { const fl = flowNameSegment(d.properties.displayName); captures[fl] = captures[fl] ?? named; }
}
const badKey = Object.entries(FLOW_IDENTITIES).filter(([, v]) => v.key !== NOKEY && !keys.has(v.key));
ok(!badKey.length, 'every contract key in FLOW_IDENTITIES is a catalogue contract key, or NOKEY', badKey.map(([n, v]) => `${n}: ${v.key}`).join(', '));
/* An id the repository holds no evidence for is not written: it is NOT_CAPTURED until a capture or export gives it. */
const badId = Object.entries(FLOW_IDENTITIES).filter(([n, v]) => (captures[n] ? v.id !== captures[n] : v.id !== NOT_CAPTURED));
ok(!badId.length, 'every flow id in FLOW_IDENTITIES is the GUID of that flow\'s tenant capture or export', badId.map(([n, v]) => `${n}: ${v.id} (capture ${captures[n] ?? 'none'})`).join(', '));
const falseGap = Object.entries(FLOW_IDENTITIES).filter(([n, v]) => v.id === NOT_CAPTURED && captures[n]);
ok(!falseGap.length, 'NOT_CAPTURED is used only for a flow the repository holds no capture or export of', falseGap.map(([n]) => n).join(', '));

/* The 8-digit id names one flow: no two flow ids the estate register knows share a prefix (a dashed and an undashed
   form of one id are one flow). */
const est = JSON.parse(readFileSync(`${ROOT}/reference/estate-register.json`, 'utf8')).flows;
const byPrefix = new Map();
for (const fl of est) for (const g of [fl.flowGuid, fl.workflowId].filter(Boolean)) {
  const full = String(g).toLowerCase().replace(/-/g, ''); const p = full.slice(0, 8);
  byPrefix.set(p, new Set([...(byPrefix.get(p) ?? []), full]));
}
const clash = [...byPrefix].filter(([, v]) => v.size > 1);
ok(byPrefix.size > 100 && !clash.length, `the first 8 hex digits of every flow id in the estate register (${byPrefix.size}) name one flow`, clash.map(([p, v]) => `${p}: ${[...v].join(', ')}`).join('; '));
const ownClash = Object.entries(FLOW_IDENTITIES).filter(([n, v]) => v.id !== NOT_CAPTURED && [...(byPrefix.get(flowIdPart(v.id)) ?? [])].some((g) => g !== v.id.replace(/-/g, '')));
ok(!ownClash.length, 'no flow in FLOW_IDENTITIES shares its 8-digit id with another estate flow', ownClash.map(([n]) => n).join(', '));

/* The packages. */
for (const dir of ['identification-phase3', 'identification-phase4', 'identification-phase5']) {
  const files = readdirSync(`${ROOT}/packages/${dir}`).filter((f) => f.endsWith('.json'));
  const bad = [];
  const perFlow = files.map(parseFlowArtifactName).filter(Boolean).reduce((m, n) => m.set(n.flow, (m.get(n.flow) ?? 0) + 1), new Map());
  for (const f of files) {
    const n = parseFlowArtifactName(f);
    if (!n) { bad.push(`${f}: not <KEY>__<flow>__<id8>[__<part>].<kind>`); continue; }
    const id = FLOW_IDENTITIES[n.flow];
    const pkg = JSON.parse(readFileSync(`${ROOT}/packages/${dir}/${f}`, 'utf8'));
    if (!id) bad.push(`${f}: flow ${n.flow} has no recorded identity`);
    else if (id.key !== n.key || flowIdPart(id.id) !== n.id) bad.push(`${f}: names ${n.key}/${n.id}, the flow is ${id.key}/${id.id}`);
    /* A part only where the folder holds more than one package for the flow, and then the scope it replaces. */
    if (perFlow.get(n.flow) > 1 ? n.part !== pkg.nodeId : n.part !== null) bad.push(`${f}: part ${n.part}; ${perFlow.get(n.flow)} package(s) for the flow, the package replaces ${pkg.nodeId}`);
    if (n.kind !== 'paste.json') bad.push(`${f}: kind ${n.kind}`);
  }
  ok(files.length > 0 && !bad.length, `${dir}: every package (${files.length}) is named <KEY>__<flow>__<flow id8>[__<root scope>].paste.json for the flow it is for`, bad.join('; '));
}

console.log(`\n${fail ? '❌' : '✅'} ${pass} passed, ${fail} failed\n`);
process.exit(fail ? 1 : 0);
